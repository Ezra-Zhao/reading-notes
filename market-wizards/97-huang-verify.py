#!/usr/bin/env python3
"""97 黄兴亮（万家优选 161903）验算脚本：十二组断言。
数据源：万家行业优选混合型证券投资基金（LOF）2026 年第 3 季度报告
（报告期 2026-07-01 至 2026-09-30，2026-10-27 送出，巨潮资讯原文 PDF）。
全部用 Decimal 精确验算；天数用 datetime.date 差。"""
from decimal import Decimal as D, getcontext
from datetime import date

getcontext().prec = 28
ok = 0

def chk(name, cond):
    global ok
    assert cond, f"FAIL: {name}"
    ok += 1
    print(f"  ok {name}")

# 1 任期与基金生命
fund0, mgr0, end = date(2005, 7, 15), date(2019, 3, 2), date(2026, 9, 30)
chk("1a 基金生命7747天", (end - fund0).days == 7747)
chk("1b 任期2769天", (end - mgr0).days == 2769)
chk("1c 上任前4978天", (mgr0 - fund0).days == 4978)
chk("1d 任期占比约35.74%", abs(D((end - mgr0).days) / D((end - fund0).days) * 100 - D("35.74")) < D("0.01"))

# 2 半年劈季：六个月 +29.02% / 三季度 -8.23% 反推二季度
q2 = (D("1.2902") / D("0.9177") - 1) * 100
q2b = (D("0.9891") / D("0.9016") - 1) * 100
chk("2a 二季度反推约+40.59%", abs(q2 - D("40.59")) < D("0.01"))
chk("2b 二季度基准反推约+9.70%", abs(q2b - D("9.70")) < D("0.01"))
chk("2c 二季度超额差约30.89pp", abs((q2 - q2b) - D("30.89")) < D("0.01"))
chk("2d 三季度回本价约+8.97%", abs((1 / D("0.9177") - 1) * 100 - D("8.97")) < D("0.01"))

# 3 八窗口印刷超额 = 净值 - 基准
rows = [("-8.23", "-9.84", "1.61"), ("29.02", "-1.09", "30.11"), ("9.72", "-4.11", "13.83"),
        ("68.38", "17.98", "50.40"), ("3.54", "-3.58", "7.12"), ("139.37", "19.79", "119.58"),
        ("264.82", "39.68", "225.14"), ("1094.01", "228.28", "865.73")]
chk("3 八窗口超额逐项对平", all(D(f) - D(b) == D(e) for f, b, e in rows))

# 4 长窗拆段
chk("4a 三至五年前一段约-38.51%", abs((D("1.0354") / D("1.6838") - 1) * 100 - D("-38.51")) < D("0.01"))
chk("4b 五至七年前一段约+131.19%", abs((D("2.3937") / D("1.0354") - 1) * 100 - D("131.19")) < D("0.01"))
chk("4c 七至十年前一段约+52.41%", abs((D("3.6482") / D("2.3937") - 1) * 100 - D("52.41")) < D("0.01"))
chk("4d 一年拆前半年约-14.96%", abs((D("1.0972") / D("1.2902") - 1) * 100 - D("-14.96")) < D("0.01"))

# 5 利润账：已实现对浮亏
real, prof = D("293177073.31"), D("-490107889.52")
flt = prof - real
chk("5a 浮亏约-7.83亿", flt == D("-783284962.83"))
chk("5b 浮亏约已实现2.67倍", abs(abs(flt) / real - D("2.67")) < D("0.01"))

# 6 波动：三季度标准差 2.65% 对基准 1.03%
chk("6a 波动约基准2.57倍", abs(D("2.65") / D("1.03") - D("2.57")) < D("0.01"))
chk("6b 印刷标准差差+1.62pp", D("2.65") - D("1.03") == D("1.62"))

# 7 净值口径：期末净值 / 期末份额 = 单位净值（四舍五入内）
navps = D("5268078888.10") / D("3182632802.35")
chk("7a 单位净值复算约1.6553", abs(navps - D("1.6553")) < D("0.0001"))
chk("7b 自成立因子与单位净值比约7.21只登记", abs(D("11.9401") / D("1.6553") - D("7.21")) < D("0.01"))

# 8 资产组合：权益/债券/现金
chk("8a 权益占总资产92.77%(印刷)", abs(D("4902201410.18") / D("5284073261.42") * 100 - D("92.77")) < D("0.01"))
chk("8b 权益占净值约93.05%", abs(D("4902201410.18") / D("5268078888.10") * 100 - D("93.05")) < D("0.01"))
chk("8c 债券占净值约3.24%且全为政策性金融债", abs(D("170691084.93") / D("5268078888.10") * 100 - D("3.24")) < D("0.01"))

# 9 行业：制造业 + 信息技术 = 93.05%
chk("9a 两行业合计93.05%", D("43.51") + D("49.54") == D("93.05"))
chk("9b 信息技术约占股票仓位53.24%", abs(D("49.54") / D("93.05") * 100 - D("53.24")) < D("0.01"))

# 10 前十大：合计与三组拆分
tops = [D(x) for x in ["9.31", "9.22", "8.49", "7.80", "7.66", "7.53", "6.14", "6.05", "5.31", "5.25"]]
chk("10a 前十大合计72.76%", sum(tops) == D("72.76"))
chip = tops[0] + tops[4] + tops[6] + tops[7] + tops[8]      # 思瑞浦/寒武纪/瑞芯微/中微/中芯
pharma = tops[3] + tops[5]                                   # 荣昌生物/百济神州
soft = tops[1] + tops[2] + tops[9]                           # 深信服/网宿科技/用友网络
chk("10b 芯片五席34.47%", chip == D("34.47"))
chk("10c 医药两席15.33%", pharma == D("15.33"))
chk("10d 软件三席22.96%且三组对平", soft == D("22.96") and chip + pharma + soft == sum(tops))
chk("10e 前十大约占股票仓位78.19%", abs(sum(tops) / D("93.05") * 100 - D("78.19")) < D("0.01"))

# 11 份额账
s0, sub, red, s1 = D("3442763935.01"), D("174268784.82"), D("434399917.48"), D("3182632802.35")
chk("11a 期初+申购-赎回=期末", s0 + sub - red == s1)
chk("11b 总份额净减约7.56%", abs((s1 - s0) / s0 * 100 - D("-7.56")) < D("0.01"))
chk("11c 赎回约申购2.49倍", abs(red / sub - D("2.49")) < D("0.01"))

# 12 七年窗口终点换算（整段落在任期内：窗口起点 2019-09-30 晚于任职日）
chk("12a 七年一万元终点23937对11979", D("10000") * D("2.3937") == D("23937") and D("10000") * D("1.1979") == D("11979"))
chk("12b 七年终点约基准2.00倍", abs(D("2.3937") / D("1.1979") - D("2.00")) < D("0.01"))

print(f"ALL {ok} assertions passed (12 groups)")
