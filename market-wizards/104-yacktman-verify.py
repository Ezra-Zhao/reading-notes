from decimal import Decimal as D, getcontext
from datetime import date

getcontext().prec = 28
ok = 0

def chk(name, cond):
    global ok
    assert cond, f"FAIL: {name}"
    ok += 1
    print(f"  ok {name}")

# 1 类别生命与 Stephen 任期区间：Class N 成立 1997-05-01；Class I 成立 2012-07-24
