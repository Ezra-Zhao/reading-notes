chk("8d 前三名合计26.46%约占前十大53.57%", sum(top10[:3]) == D("26.46") and abs(D("26.46") / sum(top10) * 100 - D("53.57")) < D("0.01"))

# 9 类别差：Class I 高 Class N 的幅度与费用差对照
diffs = [D("2.23") - D("2.18"), D("24.99") - D("24.78"), D("35.82") - D("35.52"),
         D("20.09") - D("19.88"), D("12.12") - D("11.91"), D("13.33") - D("13.13")]
