chk("1b Class N约29.42年", abs(D(life_n) / D("365.25") - D("29.42")) < D("0.01"))
chk("1c Class I成立至今5181天", life_i == 5181)
chk("1d Class I约14.18年", abs(D(life_i) / D("365.25") - D("14.18")) < D("0.01"))
lo = (date(2026, 9, 30) - date(2002, 12, 31)).days
hi = (date(2026, 9, 30) - date(2002, 12, 1)).days
chk("1e Stephen任期天数在8674至8704之间（2002年12月起任、只有月份精度）", lo == 8674 and hi == 8704)
chk("1f Stephen任期约23.75至23.83年", abs(D(lo) / D("365.25") - D("23.75")) < D("0.01") and abs(D(hi) / D("365.25") - D("23.83")) < D("0.01"))
chk("1g Stephen任期约占Class N生命约80.7%至81.0%", abs(D(lo) / D(life_n) * 100 - D("80.74")) < D("0.01") and abs(D(hi) / D(life_n) * 100 - D("81.02")) < D("0.01"))
chk("1h Class N成立至Stephen起任间隔2040至2070天为其父Don时段（只登记）", (date(2002, 12, 1) - date(1997, 5, 1)).days == 2040 and (date(2002, 12, 31) - date(1997, 5, 1)).days == 2070)

# 2 2026 年劈段：年初至今与三季度反推上半年（Class N 与两把尺子）
chk("2a 上半年基金约+22.12%", abs((D("1.2478") / D("1.0218") - 1) * 100 - D("22.12")) < D("0.01"))
chk("2b 上半年Russell价值约+16.24%", abs((D("1.1927") / D("1.0261") - 1) * 100 - D("16.24")) < D("0.01"))
chk("2c 上半年标普约+10.22%", abs((D("1.1275") / D("1.0230") - 1) * 100 - D("10.22")) < D("0.01"))
chk("2d 三季度基金跑输价值0.43pp跑输标普0.12pp为印刷行差", D("2.18") - D("2.61") == D("-0.43") and D("2.18") - D("2.30") == D("-0.12"))
chk("2e 上半年基金领先价值约5.88pp领先标普约11.90pp（反推行差）", abs(D("22.12") - D("16.24") - D("5.88")) < D("0.01") and abs(D("22.12") - D("10.22") - D("11.90")) < D("0.01"))

# 3 窗口超额逐项（Class N 对 Russell 1000 Value 与 S&P 500，印刷行差）
rows = [("2.18", "2.61", "2.30"), ("24.78", "19.27", "12.75"), ("35.52", "23.81", "15.74"),
        ("19.88", "20.07", "22.89"), ("11.91", "11.92", "13.79"), ("13.13", "11.43", "15.33"),
        ("10.53", "9.06", "9.94")]
exp_r = [D(x) for x in ["-0.43", "5.51", "11.71", "-0.19", "-0.01", "1.70", "1.47"]]
exp_s = [D(x) for x in ["-0.12", "12.03", "19.78", "-3.01", "-1.88", "-2.20", "0.59"]]
chk("3 窗口超额七行逐项", all(D(f) - D(r) == er and D(f) - D(s) == es for (f, r, s), er, es in zip(rows, exp_r, exp_s)))

# 4 累计窗口：年化印刷行机械连乘（Class N）
chk("4a 三年累计基金约+72.28%", abs(((1 + D("19.88") / 100) ** 3 - 1) * 100 - D("72.28")) < D("0.01"))
chk("4b 三年累计价值约+73.10%标普约+85.59%", abs(((1 + D("20.07") / 100) ** 3 - 1) * 100 - D("73.10")) < D("0.01") and abs(((1 + D("22.89") / 100) ** 3 - 1) * 100 - D("85.59")) < D("0.01"))
chk("4c 五年累计基金约+75.53%价值约+75.61%只差0.08pp", abs(((1 + D("11.91") / 100) ** 5 - 1) * 100 - D("75.53")) < D("0.01") and abs(((1 + D("11.92") / 100) ** 5 - 1) * 100 - D("75.61")) < D("0.01"))
chk("4d 十年累计基金约+243.38%价值约+195.14%标普约+316.32%", abs(((1 + D("13.13") / 100) ** 10 - 1) * 100 - D("243.38")) < D("0.01") and abs(((1 + D("11.43") / 100) ** 10 - 1) * 100 - D("195.14")) < D("0.01") and abs(((1 + D("15.33") / 100) ** 10 - 1) * 100 - D("316.32")) < D("0.01"))

# 5 长窗拆段：老段 = 长窗因子 / 近窗因子
chk("5a 五至十年前一段基金约+95.63%", abs(((1 + D("13.13") / 100) ** 10 / (1 + D("11.91") / 100) ** 5 - 1) * 100 - D("95.63")) < D("0.01"))
chk("5b 五至十年前一段价值约+68.07%标普约+118.22%", abs(((1 + D("11.43") / 100) ** 10 / (1 + D("11.92") / 100) ** 5 - 1) * 100 - D("68.07")) < D("0.01") and abs(((1 + D("15.33") / 100) ** 10 / (1 + D("13.79") / 100) ** 5 - 1) * 100 - D("118.22")) < D("0.01"))
chk("5c 三至五年前一段基金约+1.88%价值约+1.45%标普约+2.79%（两年近乎原地）", abs(((1 + D("11.91") / 100) ** 5 / (1 + D("19.88") / 100) ** 3 - 1) * 100 - D("1.88")) < D("0.01") and abs(((1 + D("11.92") / 100) ** 5 / (1 + D("20.07") / 100) ** 3 - 1) * 100 - D("1.45")) < D("0.01") and abs(((1 + D("13.79") / 100) ** 5 / (1 + D("22.89") / 100) ** 3 - 1) * 100 - D("2.79")) < D("0.01"))

