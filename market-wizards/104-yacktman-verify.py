# 10 一年窗成色：一年领先主要不是三季度挣的
chk("10a 三季度基金只涨2.18%而一年涨35.52%：此前约九个月约+32.63%", abs((D("1.3552") / D("1.0218") - 1) * 100 - D("32.63")) < D("0.01"))
