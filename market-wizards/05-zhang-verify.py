"""Market Wizards 05 章盟主 / 章建平验证脚本（clean-room 自写）
验本篇六笔可复算的账，数字均取公开财报与报道陈述，不冒充审计：
1) 1996 年 5 万元到 1997 年 20 万元是 4 倍（涨 300%）；
2) 云南锗业 665.98 万股增至 2627.55 万股，增量 1961.57 万股，增幅约 294.5%；
3) 亨通光电夫妻合计 3441.61+2186.84=5628.45 万股；
4) 以第十大股东 1225.67 万股为门槛，两人至少减持 2215.94+961.17=3177.11 万股（退出前十不等于清仓）；
5) 方文艳华正新材 777.47 万股占 4.96%，反推总股本约 15674.8 万股；
6) 云南锗业期末市值 22.83 亿元除以 2627.55 万股，隐含均价约 86.89 元。
"""

# 1
assert 200_000 / 50_000 == 4
assert (200_000 / 50_000 - 1) * 100 == 300
print("1 通过：5 万到 20 万是 4 倍，涨 300%")

# 2
assert round(2627.55 - 665.98, 2) == 1961.57
assert round((2627.55 / 665.98 - 1) * 100, 1) == 294.5
print("2 通过：云南锗业增持 1961.57 万股，增幅约 294.5%")

# 3
assert round(3441.61 + 2186.84, 2) == 5628.45
print("3 通过：亨通光电夫妻合计 5628.45 万股")

# 4
assert round(3441.61 - 1225.67, 2) == 2215.94
assert round(2186.84 - 1225.67, 2) == 961.17
assert round(2215.94 + 961.17, 2) == 3177.11
print("4 通过：两人至少减持合计 3177.11 万股（门槛推算，非清仓证明）")

# 5
assert round(777.47 / 0.0496, 1) == 15674.8
print("5 通过：777.47 万股 / 4.96% 反推总股本约 15674.8 万股")

# 6
