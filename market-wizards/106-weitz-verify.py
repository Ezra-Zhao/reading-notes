#!/usr/bin/env python3
"""106 Wally Weitz（Weitz Partners III Opportunity Fund WPOPX）验算脚本：十二组断言。
数据源：Weitz Partners III Opportunity Fund 3Q 2025 Commentary（Weitz Investment
Management 官方评论，数据截至 2025-09-30，意见截至 2025-10-09）：经理栏
（Wally Weitz 列首位、Drew Weitz 次位）、Institutional Class 与 Russell 3000／
Bloomberg U.S. 3000 的收益表（季度／年初至今／一年为累计行，三年起为平均年化行，
自成立日 1983-06-01）、前五大贡献与拖累表、费用比率 1.18%，以及脚注
（2005-12-30 本基金承继 Weitz Partners III Limited Partnership 绝大部分资产、
合伙企业时段业绩并入且由投资顾问全权管理）。全部用 Decimal 精确验算；
天数用 datetime.date 差。经理个人起任日不在本文件内，不作断言、只登记缺口。"""
from decimal import Decimal as D, getcontext
from datetime import date

getcontext().prec = 28
ok = 0

def chk(name, cond):
    global ok
    assert cond, f"FAIL: {name}"
    ok += 1
    print(f"  ok {name}")

# 1 业绩生命：自成立日 1983-06-01 至 2025-09-30（注意：含合伙企业前身时段，脚注口径）
life = (date(2025, 9, 30) - date(1983, 6, 1)).days
chk("1a 自成立日至2025-09-30共15462天", life == 15462)
chk("1b 约42.33年", abs(D(life) / D("365.25") - D("42.33")) < D("0.01"))
chk("1c 基金承继合伙企业日2005-12-30距成立日8248天（只登记）", (date(2005, 12, 30) - date(1983, 6, 1)).days == 8248)

# 2 2025 年劈段：年初至今与三季度反推上半年
chk("2a 上半年基金约+2.34%", abs((D("1.0249") / D("1.0015") - 1) * 100 - D("2.34")) < D("0.01"))
chk("2b 上半年Russell约+5.75%Bloomberg约+5.76%", abs((D("1.1440") / D("1.0818") - 1) * 100 - D("5.75")) < D("0.01") and abs((D("1.1448") / D("1.0825") - 1) * 100 - D("5.76")) < D("0.01"))
chk("2c 上半年基金落后Russell约3.41pp（反推行差）", abs(D("5.75") - D("2.34") - D("3.41")) < D("0.01"))
chk("2d 三季度印刷行差基金输Bloomberg8.10pp输Russell8.03pp", D("0.15") - D("8.25") == D("-8.10") and D("0.15") - D("8.18") == D("-8.03"))

# 3 窗口超额逐项（基金对 Russell 3000，印刷／年化行差）
rows = [("0.15", "8.18"), ("2.49", "14.40"), ("3.73", "17.41"), ("13.81", "24.09"),
        ("5.83", "15.73"), ("6.62", "14.70"), ("7.09", "10.74"), ("9.97", "10.33"),
        ("10.88", "11.62"), ("11.29", "11.41")]
exp = [D(x) for x in ["-8.03", "-11.91", "-13.68", "-10.28", "-9.90", "-8.08", "-3.65", "-0.36", "-0.74", "-0.12"]]
chk("3 窗口超额十行逐项对Russell", all(D(f) - D(r) == e for (f, r), e in zip(rows, exp)))

# 4 Bloomberg 对照（三季度至二十年，印刷行差）
chk("4a 对Bloomberg七行超额-8.10/-11.99/-13.70/-10.26/-9.86/-8.07/-3.74",
    [D("0.15") - D("8.25"), D("2.49") - D("14.48"), D("3.73") - D("17.43"), D("13.81") - D("24.07"),
     D("5.83") - D("15.69"), D("6.62") - D("14.69"), D("7.09") - D("10.83")] ==
    [D("-8.10"), D("-11.99"), D("-13.70"), D("-10.26"), D("-9.86"), D("-8.07"), D("-3.74")])

# 5 累计窗口：年化印刷行机械连乘（基金）
chk("5a 三年累计基金约+47.41%Russell约+91.08%", abs(((1 + D("13.81") / 100) ** 3 - 1) * 100 - D("47.41")) < D("0.01") and abs(((1 + D("24.09") / 100) ** 3 - 1) * 100 - D("91.08")) < D("0.01"))
chk("5b 五年累计基金约+32.75%Russell约+107.60%", abs(((1 + D("5.83") / 100) ** 5 - 1) * 100 - D("32.75")) < D("0.01") and abs(((1 + D("15.73") / 100) ** 5 - 1) * 100 - D("107.60")) < D("0.01"))
chk("5c 十年累计基金约+89.84%Russell约+294.13%", abs(((1 + D("6.62") / 100) ** 10 - 1) * 100 - D("89.84")) < D("0.01") and abs(((1 + D("14.70") / 100) ** 10 - 1) * 100 - D("294.13")) < D("0.01"))

# 6 长窗拆段：老段 = 长窗因子 / 近窗因子
chk("6a 三至五年前一段基金约-9.95%Russell约+8.65%（两年）", abs(((1 + D("5.83") / 100) ** 5 / (1 + D("13.81") / 100) ** 3 - 1) * 100 - D("-9.95")) < D("0.01") and abs(((1 + D("15.73") / 100) ** 5 / (1 + D("24.09") / 100) ** 3 - 1) * 100 - D("8.65")) < D("0.01"))
chk("6b 五至十年前一段基金约+43.00%Russell约+89.85%", abs(((1 + D("6.62") / 100) ** 10 / (1 + D("5.83") / 100) ** 5 - 1) * 100 - D("43.00")) < D("0.01") and abs(((1 + D("14.70") / 100) ** 10 / (1 + D("15.73") / 100) ** 5 - 1) * 100 - D("89.85")) < D("0.01"))
chk("6c 十至二十年前一段基金约+107.30%Russell约+95.19%（老段基金赢）", abs(((1 + D("7.09") / 100) ** 20 / (1 + D("6.62") / 100) ** 10 - 1) * 100 - D("107.30")) < D("0.01") and abs(((1 + D("10.74") / 100) ** 20 / (1 + D("14.70") / 100) ** 10 - 1) * 100 - D("95.19")) < D("0.01"))

# 7 自成立终点：按自成立年化机械滚算约 42.33 年
yrs = D(life) / D("365.25")
chk("7a 一万美元基金终点约926001美元", abs(10000 * (1 + D("11.29") / 100) ** yrs - D("926001")) < D("3"))
chk("7b 一万美元Russell终点约969225美元", abs(10000 * (1 + D("11.41") / 100) ** yrs - D("969225")) < D("3"))
chk("7c 基金终点约Russell的0.96倍", abs((1 + D("11.29") / 100) ** yrs / (1 + D("11.41") / 100) ** yrs - D("0.96")) < D("0.01"))

# 8 贡献与拖累：前五大两表合计与基金季度收益对照
contrib = [D(x) for x in ["1.54", "1.17", "0.95", "0.45", "0.25"]]
detr = [D(x) for x in ["-2.28", "-0.83", "-0.42", "-0.36", "-0.27"]]
chk("8a 前五大贡献合计+4.36pp", sum(contrib) == D("4.36"))
chk("8b 前五大拖累合计-4.16pp", sum(detr) == D("-4.16"))
chk("8c 十项净贡献+0.20pp与基金季度+0.15%差0.05pp只登记", sum(contrib) + sum(detr) == D("0.20") and sum(contrib) + sum(detr) - D("0.15") == D("0.05"))

# 9 持仓权重形状：Berkshire 一只压过贡献榜
chk("9a Berkshire净资产权重13.6%为贡献表内最大", D("13.6") > D("6.1") and D("13.6") > D("5.8"))
chk("9b Berkshire季度涨3.49%贡献0.45pp（印刷行）", D("3.49") > 0 and D("0.45") > 0)
chk("9c Liberty Broadband拖累-2.28pp约Alphabet贡献1.54pp的1.48倍", abs(D("2.28") / D("1.54") - D("1.48")) < D("0.01"))
chk("9d 贡献前五净资产权重合计29.5%", D("5.8") + D("1.1") + D("6.1") + D("13.6") + D("2.9") == D("29.5"))

# 10 一年窗劈段：三季度之前约九个月
chk("10a 此前约九个月基金约+3.57%", abs((D("1.0373") / D("1.0015") - 1) * 100 - D("3.57")) < D("0.01"))
chk("10b 此前约九个月Russell约+8.53%", abs((D("1.1741") / D("1.0818") - 1) * 100 - D("8.53")) < D("0.01"))
chk("10c 一年落后13.68pp中三季度单季行差占8.03pp（只作对照、两口径不可直接相加成因果）", D("8.03") < D("13.68"))

# 11 类别差：Investor Class 低于 Institutional Class 的幅度与费用对照
diffs = [D("11.29") - D("11.10"), D("10.88") - D("10.68"), D("13.81") - D("12.96")]
chk("11a 自成立/四十年/三年类别差0.19/0.20/0.85pp逐项", diffs == [D("0.19"), D("0.20"), D("0.85")])
chk("11b Institutional费用净=总=1.18%Investor净=总=1.93%差0.75pp", D("1.93") - D("1.18") == D("0.75"))

# 12 披露口径：少于一年不年化、自成立含前身合伙企业时段
chk("12a 季度0.15%与年初至今2.49%均为累计行不作年化读", D("2.49") > D("0.15"))
chk("12b 自成立年化差-0.12pp而十年年化差-8.08pp：差距主要在近十年（3/5/6组已验）", D("-0.12") > D("-8.08"))

print(f"ALL {ok} ASSERTIONS PASSED")
