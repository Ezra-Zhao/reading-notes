# -*- coding: utf-8 -*-
"""葛兰篇验算：中欧医疗健康年报口径、三季报口径与规模轨迹。"""
from datetime import date

def close(a,b,tol=0.15): return abs(a-b) <= tol

# 1 三年连乘对年报“过去三年42.54%”
chain = 1.9885*0.9345*0.7671
assert close((chain-1)*100, 42.54, 0.1), chain
print(f"1 2020-2022 A连乘 {chain:.4f} -> {(chain-1)*100:.2f}% vs 年报过去三年42.54% OK")

# 2 NAV回撤 2020末3.446 -> 2022末2.3642
dd = (2.3642-3.446)/3.446*100
rec = (3.446/2.3642-1)*100
assert close(dd, -31.39, 0.05) and close(rec, 45.76, 0.1)
print(f"2 A净值 3.446->2.3642 回撤 {dd:.2f}% 回本需 {rec:.2f}% OK")

# 3 中欧医疗健康规模 A+C 合计
s2020=10.20767871137+13.03518282571  # 年报亿元换算(元/1e8)近似取原文亿元两位
# 用年报原文(元): 2020 A 10207678711.37? 以亿元两位登记: 102.08+130.35
s2020=102.08+130.35; s2021=340.52+434.53; s2022=297.46+343.92
assert close(s2020,232.43,0.02) and close(s2021,775.05,0.02) and close(s2022,641.38,0.02)
print(f"3 医疗健康合计 2020末{s2020:.2f}亿 2021末{s2021:.2f}亿 2022末{s2022:.2f}亿 OK")

# 4 规模下行: 医疗健康2021末 -> 2026Q3 255.44
drop=(775.05-255.44)/775.05*100
assert close(drop,67.04,0.1)
print(f"4 医疗健康 775.05->255.44 少{775.05-255.44:.2f}亿 降{drop:.2f}% OK")

# 5 在管总规模 906.53(2022末,Wind/成都商报) -> 332.66(2026Q3)
tot=132.77+44.95+122.67+32.27
assert close(tot,332.66,0.01)
drop2=(906.53-332.66)/906.53*100
assert close(drop2,63.30,0.1)
print(f"5 四份额合计 {tot:.2f}亿; 总规模 906.53->332.66 降{drop2:.2f}% OK")

# 6 纳微科技增持
r=1207.06/413.23
assert close(r,2.92,0.01) and close((r-1)*100,192.10,0.5)
print(f"6 纳微 413.23->1207.06万股 {r:.2f}倍 增{(r-1)*100:.1f}% OK")

# 7 金斯瑞增持百分比复核报道口径
g=(1198.60-1.8)/1.8*100
assert close(g,66488.88,1.0)
print(f"7 金斯瑞 1.8->1198.60万股 增{g:.2f}% vs 报道66488.88% OK")

# 8 任期与年化
days=(date(2026,9,30)-date(2016,9,29)).days
yrs=days/365.25
ann=(1.9733)**(1/yrs)-1
assert days==3653, days
assert close(ann*100,7.0,0.2)
print(f"8 任期 {days}天 约{yrs:.2f}年; 任期回报97.33%即1.9733倍 机械年化{ann*100:.2f}% OK")

# 9 Q3超额
assert close(9.95-7.32,2.63,0.01)
print("9 2026Q3 A 9.95% - 基准7.32% = 超额2.63个百分点 OK")
print("ALL PASS")
