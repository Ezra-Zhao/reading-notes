ok = 0

def chk(name, cond):
    global ok
    assert cond, f"FAIL: {name}"
    ok += 1
    print(f"  ok {name}")

# 1 任期与基金生命：合同生效 2016-03-29；邢军亮 2021-11-03 起任；左腾飞 2024-02-06 起任
