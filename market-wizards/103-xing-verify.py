chk("3c 前九个月超额约-3.18pp", abs(((D("0.8322") / D("0.8184") - 1) * 100) - ((D("0.8689") / D("0.8286") - 1) * 100) - D("-3.18")) < D("0.01"))

# 4 窗口超额逐项（A 类，印刷行）
rows = [("-18.16", "-17.14", "-1.02"), ("-18.50", "-16.92", "-1.58"), ("-16.78", "-13.11", "-3.67"),
        ("0.52", "2.50", "-1.98"), ("-43.29", "-29.73", "-13.56"), ("170.19", "62.62", "107.57"),
        ("148.71", "47.95", "100.76"), ("146.87", "51.62", "95.25")]
