# 5 长窗拆段：老段 = 长窗因子 / 近窗因子
chk("5a 五至三年前一段基金约-43.58%", abs((D("0.5671") / D("1.0052") - 1) * 100 - D("-43.58")) < D("0.01"))
chk("5b 五至三年前一段基准约-31.44%", abs((D("0.7027") / D("1.0250") - 1) * 100 - D("-31.44")) < D("0.01"))
