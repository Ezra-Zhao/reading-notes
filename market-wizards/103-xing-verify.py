chk("1a 基金生命3837天", life == 3837)
chk("1b 邢任期1792天", xing == 1792)
chk("1c 左任期967天", zuo == 967)
chk("1d 邢任期约4.91年占生命约46.70%", abs(D(xing) / D("365.25") - D("4.91")) < D("0.01") and abs(D(xing) / D(life) * 100 - D("46.70")) < D("0.01"))
chk("1e 左任期约2.65年占生命约25.20%", abs(D(zuo) / D("365.25") - D("2.65")) < D("0.01") and abs(D(zuo) / D(life) * 100 - D("25.20")) < D("0.01"))
chk("1f 五年窗起点2021-09-30距邢上任34天", (date(2021, 11, 3) - date(2021, 9, 30)).days == 34)

# 2 2026 年内劈段：六个月与三季度反推二季度（A 类）
