chk("6a 三季度跌18.16%回本需约+22.19%", abs((D("1") / D("0.8184") - 1) * 100 - D("22.19")) < D("0.01"))
chk("6b 五年跌43.29%回本需约+76.34%", abs((D("1") / D("0.5671") - 1) * 100 - D("76.34")) < D("0.01"))

