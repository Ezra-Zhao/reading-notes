chk("11c 行业四行合计69.16%与权益占净值一致", D("2.49") + D("63.48") + D("0.89") + D("2.30") == D("69.16"))
chk("11d 制造业占权益约91.79%", abs(D("63.48") / D("69.16") * 100 - D("91.79")) < D("0.01"))

# 12 波动差与 C 类只登记
