chk("2b 二季度基准约+0.27%", abs((D("0.8308") / D("0.8286") - 1) * 100 - D("0.27")) < D("0.01"))
chk("2c 三季度超额-1.02pp为印刷行", D("-18.16") - D("-17.14") == D("-1.02"))
chk("2d 二季度超额约-0.68pp", abs(((D("0.8150") / D("0.8184") - 1) * 100) - ((D("0.8308") / D("0.8286") - 1) * 100) - D("-0.68")) < D("0.01"))

# 3 一年窗劈段：三季度之前的九个月
chk("3a 前九个月基金约+1.69%", abs((D("0.8322") / D("0.8184") - 1) * 100 - D("1.69")) < D("0.01"))
