#!/usr/bin/env python3
"""107 徐彦（大成竞争优势混合 090013）验算脚本：十二组断言。
数据源：大成竞争优势混合型证券投资基金 2026 年第 3 季度报告（巨潮资讯原文 PDF，
报告送出日期 2026-10-27，报告期截至 2026-09-30）：§2 合同生效日 2014-04-22
（注 1：同日由大成保本混合转型而来）、§3.1 财务指标、§3.2.1 A 类净值表现表、
§4.1 基金经理表（徐彦一人、2019-12-30 起任、离任空、从业 20 年）、§4.4 运作分析、
§5.1 资产组合、§5.2 行业、§5.3 前十大（A+H 合并排序口径）、§6 份额变动。
全部用 Decimal 精确验算；天数用 datetime.date 差。"""
from decimal import Decimal as D, getcontext
from datetime import date

getcontext().prec = 28
ok = 0

def chk(name, cond):
    global ok
    assert cond, f"FAIL: {name}"
    ok += 1
    print(f"  ok {name}")

# 1 任期与生命：徐彦 2019-12-30 起任至 2026-09-30；基金 2014-04-22 转型生效
ten = (date(2026, 9, 30) - date(2019, 12, 30)).days
life = (date(2026, 9, 30) - date(2014, 4, 22)).days
chk("1a 徐彦任期2466天", ten == 2466)
chk("1b 任期约6.75年", abs(D(ten) / D("365.25") - D("6.75")) < D("0.01"))
chk("1c 基金生命4544天约12.44年", life == 4544 and abs(D(life) / D("365.25") - D("12.44")) < D("0.01"))
chk("1d 任期占基金生命约54.27%", abs(D(ten) / D(life) * 100 - D("54.27")) < D("0.01"))

# 2 2026 年劈段：六个月与三季度反推二季度
chk("2a 二季度基金约-5.66%", abs((D("1.0189") / D("1.08") - 1) * 100 - D("-5.66")) < D("0.01"))
chk("2b 二季度基准约+7.57%", abs((D("0.9893") / D("0.9197") - 1) * 100 - D("7.57")) < D("0.01"))
chk("2c 二季度落后约13.22pp三季度印刷行差赢16.03pp", abs(D("-5.66") - D("7.57") - D("-13.22")) < D("0.02") and D("8.00") - D("-8.03") == D("16.03"))

# 3 窗口全表超额（A 类印刷行差）
rows = [("8.00", "-8.03"), ("1.89", "-1.07"), ("1.27", "-4.52"), ("34.02", "18.75"),
        ("52.24", "-3.31"), ("133.49", "19.36"), ("129.11", "39.07"), ("342.93", "100.03")]
exp = [D(x) for x in ["16.03", "2.96", "5.79", "15.27", "55.55", "114.13", "90.04", "242.90"]]
chk("3 窗口超额八行逐项", all(D(f) - D(b) == e for (f, b), e in zip(rows, exp)))

# 4 一年窗劈段：三季度之前约九个月
chk("4a 此前九个月基金约-6.23%", abs((D("1.0127") / D("1.08") - 1) * 100 - D("-6.23")) < D("0.01"))
chk("4b 此前九个月基准约+3.82%", abs((D("0.9548") / D("0.9197") - 1) * 100 - D("3.82")) < D("0.01"))
chk("4c 一年只赢5.79pp而三季度单季赢16.03pp：赢幅全在三季度且先把九个月的落后填回", D("16.03") > D("5.79"))

# 5 长窗拆段（除法拆段）
chk("5a 三至五年前一段基金约+13.59%基准约-18.58%", abs((D("1.5224") / D("1.3402") - 1) * 100 - D("13.59")) < D("0.01") and abs((D("0.9669") / D("1.1875") - 1) * 100 - D("-18.58")) < D("0.01"))
chk("5b 五至七年前一段基金约+53.37%基准约+23.45%", abs((D("2.3349") / D("1.5224") - 1) * 100 - D("53.37")) < D("0.01") and abs((D("1.1936") / D("0.9669") - 1) * 100 - D("23.45")) < D("0.01"))
chk("5c 七至十年前一段基金约-1.88%基准约+16.51%（此段大半在徐彦上任前）", abs((D("2.2911") / D("2.3349") - 1) * 100 - D("-1.88")) < D("0.01") and abs((D("1.3907") / D("1.1936") - 1) * 100 - D("16.51")) < D("0.01"))
chk("5d 十年前更早一段基金约+93.33%基准约+43.84%（全段在徐彦上任前、只登记）", abs((D("4.4293") / D("2.2911") - 1) * 100 - D("93.33")) < D("0.01") and abs((D("2.0003") / D("1.3907") - 1) * 100 - D("43.84")) < D("0.01"))

# 6 自成立机械年化与五年年化
yrs = D(life) / D("365.25")
chk("6a 自成立机械年化基金约12.71%基准约5.73%", abs((D("4.4293") ** (D(1) / yrs) - 1) * 100 - D("12.71")) < D("0.01") and abs((D("2.0003") ** (D(1) / yrs) - 1) * 100 - D("5.73")) < D("0.01"))
chk("6b 五年机械年化基金约8.77%（五年窗全在徐彦任期内）", abs((D("1.5224") ** D("0.2") - 1) * 100 - D("8.77")) < D("0.01"))

# 7 三季度成色：已实现与利润（A+C 合计）
rt = D("22922274.59") + D("8875592.36")
pt = D("198593949.18") + D("85642933.90")
chk("7a 两类已实现合计约0.32亿元", rt == D("31797866.95"))
chk("7b 两类利润合计约2.84亿元", pt == D("284236883.08"))
chk("7c 浮动部分约2.52亿元占利润约88.81%", pt - rt == D("252439016.13") and abs((pt - rt) / pt * 100 - D("88.81")) < D("0.01"))
chk("7d 利润约已实现的8.94倍", abs(pt / rt - D("8.94")) < D("0.01"))

# 8 组合形状：权益、现金、债券（占总资产印刷行）与净值口径
nav = D("2668848210.77") + D("1275882566.57")
chk("8a 期末净值合计约39.45亿元", nav == D("3944730777.34"))
chk("8b 权益占总资产60.12%现金存款35.78%债券3.71%（印刷行）", D("60.12") + D("35.78") + D("3.71") == D("99.61"))
chk("8c 权益占净值约60.26%境内42.48%加港股17.79%约60.27%尾差0.01只登记", abs(D("2377251618.00") / nav * 100 - D("60.26")) < D("0.01") and D("42.48") + D("17.79") == D("60.27"))

# 9 前十大（A+H 同名合并口径逐项相加）
top = [D("8.85"), D("1.97") + D("5.93"), D("4.34"), D("2.40") + D("1.59"), D("2.34") + D("0.95"),
       D("3.21"), D("2.85"), D("0.90") + D("1.40"), D("1.87"), D("1.73")]
chk("9a 前十大合并合计40.33%", sum(top) == D("40.33"))
chk("9b 第一名普洛药业8.85%约为第二名中国移动合并7.90%的1.12倍", abs(D("8.85") / D("7.90") - D("1.12")) < D("0.01"))

# 10 份额去留：赢十六个点的季度
chk("10a A类份额净减约0.91%", abs((D("1274413610.04") / D("1286125870.72") - 1) * 100 - D("-0.91")) < D("0.01"))
chk("10b C类份额净增约12.34%", abs((D("621641407.03") / D("553344639.90") - 1) * 100 - D("12.34")) < D("0.01"))
chk("10c 总份额净增约3.08%", abs((D("1896055017.07") / D("1839470510.62") - 1) * 100 - D("3.08")) < D("0.01"))

# 11 波动形状：各窗基金标准差均低于基准（印刷行差逐窗为负）
chk("11a 八窗波动差均为负-0.32/-0.36/-0.29/-0.13/-0.13/-0.03/+0.13/+0.27中前六窗为负",
    all(D(x) < 0 for x in ["-0.32", "-0.36", "-0.29", "-0.13", "-0.13", "-0.03"]) and D("0.13") > 0 and D("0.27") > 0)

# 12 类别差：A 与 C 三季度差及 C 类起点口径
chk("12a 三季度A高C约0.17pp", D("8.00") - D("7.83") == D("0.17"))
chk("12b C类自2023-05-11增设其自生效31.21%与A类342.93%起点不同不可直接比（只登记）", D("31.21") < D("342.93"))

print(f"ALL {ok} ASSERTIONS PASSED")
