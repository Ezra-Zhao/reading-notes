from decimal import Decimal as D, getcontext
from datetime import date

getcontext().prec = 28
ok = 0

def chk(name, cond):
    global ok
    assert cond, f"FAIL: {name}"
    ok += 1
    print(f"  ok {name}")

# 1 基金生命与经理任期：成立 2004-11-01 与三位首任经理起任同月
life = (date(2026, 9, 30) - date(2004, 11, 1)).days
chk("1a 基金成立至今8003天", life == 8003)
chk("1b 基金生命约21.91年", abs(D(life) / D("365.25") - D("21.91")) < D("0.01"))
lo_a = (date(2026, 9, 30) - date(2012, 4, 30)).days
hi_a = (date(2026, 9, 30) - date(2012, 4, 1)).days
chk("1c Ansari任期天数在5266至5295之间（2012年4月起任、只有月份精度）", lo_a == 5266 and hi_a == 5295)
lo_m = (date(2026, 9, 30) - date(2014, 1, 31)).days
hi_m = (date(2026, 9, 30) - date(2014, 1, 1)).days
chk("1d Marchetti任期天数在4625至4655之间（2014年1月起任、只有月份精度）", lo_m == 4625 and hi_m == 4655)
chk("1e Kolokotrones从业56年减在PRIMECAP43年等于入司前13年（印刷行差）", D("56") - D("43") == D("13"))

# 2 窗口超额逐项（基金对 S&P 500，印刷行差，六窗全正）
rows = [("28.00", "12.75"), ("38.93", "15.74"), ("28.83", "22.89"),
        ("16.27", "13.79"), ("16.18", "15.33"), ("12.99", "11.21")]
exp = [D(x) for x in ["15.25", "23.19", "5.94", "2.48", "0.85", "1.78"]]
chk("2 窗口超额六行逐项全正", all(D(f) - D(s) == e for (f, s), e in zip(rows, exp)))

# 3 累计窗口：年化印刷行机械连乘
chk("3a 三年累计基金约+113.82%标普约+85.59%", abs(((1 + D("28.83") / 100) ** 3 - 1) * 100 - D("113.82")) < D("0.01") and abs(((1 + D("22.89") / 100) ** 3 - 1) * 100 - D("85.59")) < D("0.01"))
chk("3b 五年累计基金约+112.49%标普约+90.77%", abs(((1 + D("16.27") / 100) ** 5 - 1) * 100 - D("112.49")) < D("0.01") and abs(((1 + D("13.79") / 100) ** 5 - 1) * 100 - D("90.77")) < D("0.01"))
chk("3c 十年累计基金约+348.04%标普约+316.32%", abs(((1 + D("16.18") / 100) ** 10 - 1) * 100 - D("348.04")) < D("0.01") and abs(((1 + D("15.33") / 100) ** 10 - 1) * 100 - D("316.32")) < D("0.01"))

# 4 长窗拆段：老段 = 长窗因子 / 近窗因子
chk("4a 五至十年前一段基金约+110.85%标普约+118.22%（该段基金输）", abs(((1 + D("16.18") / 100) ** 10 / (1 + D("16.27") / 100) ** 5 - 1) * 100 - D("110.85")) < D("0.01") and abs(((1 + D("15.33") / 100) ** 10 / (1 + D("13.79") / 100) ** 5 - 1) * 100 - D("118.22")) < D("0.01"))
chk("4b 三至五年前一段基金约-0.62%标普约+2.79%（两年基金原地略亏）", abs(((1 + D("16.27") / 100) ** 5 / (1 + D("28.83") / 100) ** 3 - 1) * 100 - D("-0.62")) < D("0.01") and abs(((1 + D("13.79") / 100) ** 5 / (1 + D("22.89") / 100) ** 3 - 1) * 100 - D("2.79")) < D("0.01"))

# 5 自成立终点：按印刷年化机械滚算约 21.91 年
yrs = D(life) / D("365.25")
