# 7 日历年累计与子段
def cum(seg):
    a = D(1); b = D(1)
    for _, f, s in seg:
        a *= 1 + D(f) / 100; b *= 1 + D(s) / 100
    return (a - 1) * 100, (b - 1) * 100
f_all, s_all = cum(cal)
chk("7a 2005-2025日历年累计基金约+935.72%标普约+745.70%", abs(f_all - D("935.72")) < D("0.01") and abs(s_all - D("745.70")) < D("0.01"))
