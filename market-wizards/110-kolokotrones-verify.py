chk("5b 一万美元标普终点约102579美元", abs(10000 * (1 + D("11.21") / 100) ** yrs - D("102579")) < D("2"))
chk("5c 基金终点约标普1.42倍", abs((1 + D("12.99") / 100) ** yrs / (1 + D("11.21") / 100) ** yrs - D("1.42")) < D("0.01"))

