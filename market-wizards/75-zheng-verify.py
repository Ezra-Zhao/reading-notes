from datetime import date

ok = []
def chk(name, cond, detail=""):
    ok.append(cond)
    print(("PASS" if cond else "FAIL"), name, detail)

def approx(a, b, tol=0.011):
    return abs(a - b) <= tol

# 1 任期：2016-09-27 任职（与合同生效日同日，首任）至 2026-09-30
d = (date(2026, 9, 30) - date(2016, 9, 27)).days
chk("1-tenure", d == 3655 and approx(d / 365.25, 10.01, 0.01), f"days={d} years={d/365.25:.2f}")

# 2 A 类八窗口超额逐项 = 净值增长率 - 基准收益率
rows = [(-31.76, -19.49, -12.27), (33.75, 12.75, 21.00), (44.30, 7.56, 36.74),
        (251.05, 61.30, 189.75), (168.36, 43.92, 124.44), (416.62, 66.48, 350.14),
        (665.64, 47.26, 618.38), (665.64, 48.77, 616.87)]
chk("2-excess", all(approx(a - b, c, 0.005) for a, b, c in rows), "8 windows")

# 3 半年劈两季：二季度单季反推（A 类）
