chk("11c 其余九只合计31.6%与第一名30.5%只差1.1个百分点", sum(top10[1:]) == D("31.6") and sum(top10[1:]) - D("30.5") == D("1.1"))
chk("11d SpaceX三季度贡献-4.01约当基金季度跌幅6.22的64.47%", abs(D("4.01") / D("6.22") * 100 - D("64.47")) < D("0.01"))

# 12 换手与口径登记
chk("12a 三年平均换手5.11%的倒数约19.57（机械读法、非官方平均持有期）", abs(D("100") / D("5.11") - D("19.57")) < D("0.01"))
chk("12b 50家发行人占净值98.1%机械平均每家约1.96%（只登记读法）", abs(D("98.1") / D("50") - D("1.96")) < D("0.01"))
chk("12c 指数自成立起算日脚注1987-06-30与基金成立日1987-06-12差18天只登记", (date(1987, 6, 30) - date(1987, 6, 12)).days == 18)

