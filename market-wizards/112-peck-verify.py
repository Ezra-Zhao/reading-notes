# 8 日历年累计与子段
def cum(seg, idx):
    a = D(1)
    for r in seg:
        a *= 1 + D(r[idx]) / 100
    return (a - 1) * 100
chk("8a 2016-2025日历年累计基金约+195.53%主尺约+224.52%宽尺约+280.16%", abs(cum(cal, 1) - D("195.53")) < D("0.01") and abs(cum(cal, 2) - D("224.52")) < D("0.01") and abs(cum(cal, 3) - D("280.16")) < D("0.01"))
chk("8b 最早五年2016-2020累计基金约+148.16%主尺约+135.24%", abs(cum(cal[:5], 1) - D("148.16")) < D("0.01") and abs(cum(cal[:5], 2) - D("135.24")) < D("0.01"))
chk("8c 最近五年2021-2025累计基金约+19.09%主尺约+37.95%宽尺约+85.47%", abs(cum(cal[5:], 1) - D("19.09")) < D("0.01") and abs(cum(cal[5:], 2) - D("37.95")) < D("0.01") and abs(cum(cal[5:], 3) - D("85.47")) < D("0.01"))

# 9 2022 年大跌的回本路
chk("9a 跌25.87%回本需约+34.90%", abs((1 / D("0.7413") - 1) * 100 - D("34.90")) < D("0.01"))
a = D("0.7413") * (1 + D("17.35") / 100)
chk("9b 加2023年仍约-13.01%", abs((a - 1) * 100 - D("-13.01")) < D("0.01"))
a *= 1 + D("10.77") / 100
chk("9c 加2024年仍约-3.64%", abs((a - 1) * 100 - D("-3.64")) < D("0.01"))
a *= 1 + D("8.20") / 100
chk("9d 加2025年才约+4.26%越过跌前", abs((a - 1) * 100 - D("4.26")) < D("0.01"))

# 10 短窗劈段
chk("10a 2026上半年反推基金约+9.68%主尺约+7.27%宽尺约+10.87%", abs((D("1.0286") / D("0.9378") - 1) * 100 - D("9.68")) < D("0.01") and abs((D("1.0101") / D("0.9416") - 1) * 100 - D("7.27")) < D("0.01") and abs((D("1.1242") / D("1.0140") - 1) * 100 - D("10.87")) < D("0.01"))
chk("10b 一年窗此前一季（2025四季度）反推基金约+7.88%主尺约-3.70%", abs((D("1.1097") / D("1.0286") - 1) * 100 - D("7.88")) < D("0.01") and abs((D("0.9727") / D("1.0101") - 1) * 100 - D("-3.70")) < D("0.01"))

# 11 前十大与单名集中
top10 = [D(x) for x in ["30.5", "4.9", "3.8", "3.8", "3.7", "3.6", "3.4", "3.2", "2.8", "2.4"]]
chk("11a 前十大逐行合计62.1%与印刷合计62.0%差0.1为取舍只登记", sum(top10) == D("62.1") and sum(top10) - D("62.0") == D("0.1"))
