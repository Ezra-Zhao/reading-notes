"""Market Wizards 02 Livermore 验证脚本（clean-room 自写）
验本篇六笔可复算的账，数字均取篇内陈述，不冒充审计或实测：
1) 1907 年后净值约 300 万、棉花一役丢约九成，只剩约 30 万；
2) 1934 年破产资产 84,000 对债务 2,500,000，覆盖率 3.36%；
3) 摊平组：100@100+100@90+100@80，成本 27,000、均价 90、市值 24,000、亏 3,000（11.1%）；
4) 金字塔组：100@100+100@110+100@120，成本 33,000、均价 110、市值 36,000、盈 3,000；
   试探单 100@100 跌到 90 砍掉，亏损封顶 1,000；
5) 单笔亏损硬顶一成、连亏五笔，资本剩 0.9**5 约 59%，仍过半；
6) 1929 年浮亏 600 万只占最终 1 亿的 6%；1 亿是 300 万的 33.3 倍。
"""

# 1
worth_1907 = 3_000_000
assert round(worth_1907 * (1 - 0.9)) == 300_000
print("1 通过：300 万丢九成剩 30 万")

# 2
assert round(84_000 / 2_500_000 * 100, 2) == 3.36
print("2 通过：8.4 万 / 250 万 = 3.36%")

# 3
cost_avg_down = 100 * 100 + 100 * 90 + 100 * 80
assert cost_avg_down == 27_000
assert cost_avg_down / 300 == 90
assert 300 * 80 == 24_000
assert cost_avg_down - 24_000 == 3_000
assert round(3_000 / cost_avg_down * 100, 1) == 11.1
print("3 通过：摊平成本 27000、均价 90、亏 3000（11.1%），股数在错误方向翻三倍")

# 4
cost_pyr = 100 * 100 + 100 * 110 + 100 * 120
assert cost_pyr == 33_000 and cost_pyr / 300 == 110
assert 300 * 120 - cost_pyr == 3_000
assert (100 - 90) * 100 == 1_000
print("4 通过：金字塔成本 33000、均价 110、盈 3000；试探单止损封顶 1000")

# 5
assert round(0.9 ** 5, 4) == 0.5905 and 0.9 ** 5 > 0.5
print("5 通过：连亏五笔各一成，资本剩约 59.05%，仍过半")

# 6
assert 6_000_000 / 100_000_000 == 0.06
assert round(100_000_000 / 3_000_000, 1) == 33.3
print("6 通过：浮亏 600 万 = 1 亿的 6%；1 亿 / 300 万 = 33.3 倍")

print("全部六项断言通过")
