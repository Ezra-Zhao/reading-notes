from datetime import date
from math import prod

ok = []
def chk(name, cond, val):
    ok.append(cond)
    print(f"{'PASS' if cond else 'FAIL'} {name}: {val}")

# 1 任期与基金生命 (起始日1997-01-01为B口径; 招募书只到年份1997)
tenure = (date(2025,12,31) - date(1997,1,1)).days
life = (date(2025,12,31) - date(1983,1,17)).days
chk("1 tenure", tenure == 10591, f"{tenure}天 约{tenure/365.25:.2f}年; 基金生命{life}天 约{life/365.25:.2f}年; 任期占{tenure/life*100:.2f}%; 上任前{(date(1997,1,1)-date(1983,1,17)).days}天")

# 2 逐年连乘 vs 十年年化20.77%
yrs = [6.12,36.90,-4.46,38.52,67.69,22.73,-33.74,47.33,37.31,24.42]
f = prod(1+x/100 for x in yrs)
chk("2 compound10", abs(f - (1.2077)**10) < 0.02, f"十年连乘因子{f:.4f} 累计{(f-1)*100:.2f}%; 年化反推{f**0.1*100-100:.2f}% vs 表载20.77%; 一万美元终点约{10000*f:,.0f}美元")

# 3 超额 vs 两指数 (1/5/10年)
fund=[24.42,15.40,20.77]; g=[18.15,14.59,17.59]; b=[17.15,13.15,14.29]
