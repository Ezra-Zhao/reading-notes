chk("3 excess", ex_g==[6.27,0.81,3.18] and ex_b==[7.27,2.25,6.48], f"对成长指数超额{ex_g}; 对罗素3000超额{ex_b}; 十年终点对成长指数{(1.2077**10)/(1.1759**10):.4f}倍")

# 4 拆段: 前五年2016-2020 vs 后五年2021-2025
f1=prod(1+x/100 for x in yrs[:5]); f2=prod(1+x/100 for x in yrs[5:])
chk("4 split", abs(f2**0.2*100-100-15.40)<0.05, f"前五年累计{(f1-1)*100:.2f}% 年化{f1**0.2*100-100:.2f}%; 后五年累计{(f2-1)*100:.2f}% 年化{f2**0.2*100-100:.2f}% vs 表载五年15.40%")

# 5 负年份与极值年
neg=[(2016+i,x) for i,x in enumerate(yrs) if x<0]
chk("5 negatives", neg==[(2018,-4.46),(2022,-33.74)], f"负年份{neg}; 最好2020 +67.69%; 最差2022 -33.74%")

# 6 回本算术: -33.74% 后
need = 1/(1-0.3374)-1
two = (1-0.3374)*(1+0.4733)
three = two*(1+0.3731)
chk("6 rebound", abs(need*100-50.91)<0.02 and two<1<three, f"回本需+{need*100:.2f}%; 2023 +47.33%后两年连乘{(two-1)*100:.2f}% 仍差{(1-two)*100:.2f}%; 加2024后累计对跌前{(three-1)*100:.2f}%")

# 7 季度极值
chk("7 quarters", abs(40.62-(-25.00)-65.62)<1e-9, f"最高季+40.62%(2020Q2) 最低季-25.00%(2022Q2) 相距65.62pp; 最低季回本需+{ (1/0.75-1)*100:.2f}%")

