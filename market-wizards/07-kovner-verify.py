"""Market Wizards 07 Kovner 验证脚本（clean-room 自写）
验本篇六笔可复算的账，数字均取公开报道陈述（Forbes／维基百科口径），不冒充审计：
1) 第一笔大豆：峰值 40,000 / 本金 3,000 约 13.33 倍；
2) 回吐 40,000-23,000=17,000，占峰值 42.5%；
3) 落袋 23,000 / 3,000 约 7.67 倍，净赚 20,000 即约 666.7%；
4) 年均 21% 连滚 28 年约 208.0 倍；
5) 年均 11% 连滚 28 年约 18.58 倍，前者约为后者 11.2 倍；
6) 年限账：1983 创立至 2011 退休恰 28 年，1992 关闭新投资者距创立 9 年，1977 第一笔至 1983 创立隔 6 年。
"""
assert round(40000 / 3000, 2) == 13.33
print("1 通过：40,000/3,000 约 13.33 倍（峰值对本金）")
assert 40000 - 23000 == 17000 and round(17000 / 40000 * 100, 1) == 42.5
print("2 通过：回吐 17,000 美元，占峰值 42.5%")
assert round(23000 / 3000, 2) == 7.67 and round(20000 / 3000 * 100, 1) == 666.7
print("3 通过：落袋约 7.67 倍，净赚 20,000 美元约 666.7%")
assert round(1.21 ** 28, 1) == 208.0
print("4 通过：年均 21% 连滚 28 年约 208.0 倍")
assert round(1.11 ** 28, 2) == 18.58 and round((1.21 ** 28) / (1.11 ** 28), 1) == 11.2
print("5 通过：年均 11% 连滚 28 年约 18.58 倍，两者差约 11.2 倍")
assert 2011 - 1983 == 28 and 1992 - 1983 == 9 and 1983 - 1977 == 6
print("6 通过：掌舵 28 年、创立后 9 年关门、第一笔后 6 年创立")
print("全部六项断言通过")
