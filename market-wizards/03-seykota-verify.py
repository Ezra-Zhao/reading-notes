"""Market Wizards 03 Seykota 验证脚本（clean-room 自写）
验本篇六笔可复算的账，数字均取篇内陈述，不冒充审计或实测：
1) 5,000 到 15,000,000 是 3,000 倍；
2) 3,000 倍按 16 年折算年复合约 64.9%；
3) 单笔风险 1%，连亏 20 笔剩约 81.8%；单笔 5% 连亏 20 笔只剩约 35.8%；
4) 一笔 +30R 盖 25 次 -1R 后净剩 +5R；
5) 胜率 40%、平均盈利 3R、平均亏损 1R，期望 +0.6R；
6) 书中逾 250,000% 现金口径小于 3,000 倍对应的 300,000% 量级，两口径不矛盾。
"""

# 1
assert 15_000_000 / 5_000 == 3000
print("1 通过：1500 万 / 5000 = 3000 倍")

# 2
cagr = (15_000_000 / 5_000) ** (1 / 16) - 1
assert round(cagr * 100, 1) == 64.9
print("2 通过：3000 倍 / 16 年，年复合约 64.9%")

# 3
assert round(0.99 ** 20 * 100, 1) == 81.8
assert round(0.95 ** 20 * 100, 1) == 35.8
print("3 通过：1% 连亏 20 笔剩 81.8%；5% 连亏 20 笔剩 35.8%")

# 4
assert 30 - 25 * 1 == 5
print("4 通过：+30R - 25R = +5R")

# 5
assert round(0.4 * 3 - 0.6 * 1, 1) == 0.6
print("5 通过：胜率 40%、盈亏比 3:1，期望 +0.6R")

# 6
assert 250_000 < 300_000
assert round((15_000_000 - 5_000) / 5_000 * 100) == 299_900
print("6 通过：现金口径逾 250,000% 与终值倍数 299,900% 增幅不是同一口径")

print("全部六项断言通过")
