#!/usr/bin/env python3
# 113 张明昕（华商优势行业混合 A 000390）验算脚本
# 源：华商优势行业灵活配置混合型证券投资基金 2026 年第 3 季度报告（巨潮原文 PDF）
# 全部用 Decimal / datetime 复算印刷数字；断言失败即退出非零。
from decimal import Decimal as D, getcontext
from datetime import date
getcontext().prec = 28
ok = 0
def chk(cond, label):
    global ok
    assert cond, f"FAIL: {label}"
    ok += 1
    print(f"  ok {label}")

def seg(total_pct, later_pct):
    """由累计窗 total 与其内后段 later 反推前段涨幅(%)"""
    return ((D(str(total_pct)) / 100 + 1) / (D(str(later_pct)) / 100 + 1) - 1) * 100

print("第1组 身份与任期")
fund_start, mgr_start, end = date(2013, 12, 11), date(2025, 3, 12), date(2026, 9, 30)
life = (end - fund_start).days; tenure = (end - mgr_start).days; pre = life - tenure
chk(life == 4676, f"基金生命 {life} 天")
chk(tenure == 567, f"张明昕任期 {tenure} 天")
chk(pre == 4109, f"上任前 {pre} 天")
chk(abs(D(tenure) / D(life) * 100 - D("12.13")) < D("0.01"), f"任期占比 {D(tenure)/D(life)*100:.2f}%")
chk(abs(D(life) / D("365.25") - D("12.80")) < D("0.01"), "基金生命约 12.80 年")
chk(abs(D(tenure) / D("365.25") - D("1.55")) < D("0.01"), "任期约 1.55 年")

print("第2组 三季度与半年劈段（A类）")
q3, bench_q3 = D("-32.84"), D("-11.78")
chk(q3 - bench_q3 == D("-21.06"), "三季度超额 -21.06 与印刷一致")
half, bench_half = D("29.20"), D("-3.87")
q2 = seg(half, q3); bench_q2 = seg(bench_half, bench_q3)
chk(abs(q2 - D("92.38")) < D("0.01"), f"二季度反推 {q2:.2f}%")
chk(abs(bench_q2 - D("8.97")) < D("0.01"), f"基准二季度反推 {bench_q2:.2f}%")
chk(abs((q2 - bench_q2) - D("83.41")) < D("0.02"), f"二季度超额约 {q2-bench_q2:.2f} 个点")

print("第3组 全表超额（A类八窗）")
rows = [("三个月", "-32.84", "-11.78", "-21.06"), ("六个月", "29.20", "-3.87", "33.07"),
        ("一年", "67.10", "-5.60", "72.70"), ("三年", "211.45", "12.58", "198.87"),
        ("五年", "248.28", "0.73", "247.55"), ("七年", "641.44", "20.49", "620.95"),
        ("十年", "924.30", "38.80", "885.50"), ("自成立", "2028.90", "77.58", "1951.32")]
for name, f, b, ex in rows:
    chk(D(f) - D(b) == D(ex), f"{name}超额 {ex} 与印刷一致")
neg = [r for r in rows if D(r[3]) < 0]
chk(len(neg) == 1 and neg[0][0] == "三个月", "八窗超额只有三个月窗为负")

print("第4组 一年窗劈段")
prior9 = seg(D("67.10"), q3); bench_prior9 = seg(D("-5.60"), bench_q3)
chk(abs(prior9 - D("148.81")) < D("0.01"), f"此前九个月反推 {prior9:.2f}%")
chk(abs(bench_prior9 - D("7.01")) < D("0.01"), f"基准此前九个月 {bench_prior9:.2f}%")
chk(abs((prior9 - bench_prior9) - D("141.80")) < D("0.02"), "此前九个月领先约 141.80 个点")

print("第5组 长窗拆段")
s5_10 = seg(D("924.30"), D("248.28")); b5_10 = seg(D("38.80"), D("0.73"))
chk(abs(s5_10 - D("194.10")) < D("0.02"), f"五至十年前一段 {s5_10:.2f}%")
chk(abs(b5_10 - D("37.79")) < D("0.02"), f"基准同段 {b5_10:.2f}%")
s3_5 = seg(D("248.28"), D("211.45")); b3_5 = seg(D("0.73"), D("12.58"))
chk(abs(s3_5 - D("11.83")) < D("0.02"), f"三至五年前一段 {s3_5:.2f}%")
chk(abs(b3_5 - D("-10.53")) < D("0.02"), f"基准同段 {b3_5:.2f}%")
s5_7 = seg(D("641.44"), D("248.28")); b5_7 = seg(D("20.49"), D("0.73"))
chk(abs(s5_7 - D("112.89")) < D("0.02"), f"五至七年前一段 {s5_7:.2f}%")
chk(abs(b5_7 - D("19.62")) < D("0.02"), f"基准同段 {b5_7:.2f}%")
s_pre10 = seg(D("2028.90"), D("924.30")); b_pre10 = seg(D("77.58"), D("38.80"))
chk(abs(s_pre10 - D("107.84")) < D("0.02"), f"十年前以前一段 {s_pre10:.2f}%")
chk(abs(b_pre10 - D("27.94")) < D("0.02"), f"基准同段 {b_pre10:.2f}%")

print("第6组 回本价")
need = (1 / (1 + q3 / 100) - 1) * 100
chk(abs(need - D("48.90")) < D("0.01"), f"跌 32.84% 回本需 {need:.2f}%")
chk(abs(q2 - need) > D("40"), "二季度涨幅远大于三季度回本价（两段不对称只登记）")

print("第7组 利润成色（A+C 合并）")
realized = D("784553171.04") + D("178534961.78")
profit = D("-5099463405.17") + D("-1166970608.99")
fv = profit - realized
chk(realized == D("963088132.82"), f"两类已实现合计 {realized} 元（约 9.63 亿）")
chk(profit == D("-6266434014.16"), f"两类利润合计 {profit} 元（约 -62.66 亿）")
chk(abs(fv - D("-7229522146.98")) < D("0.01"), f"公允价值变动约 {fv} 元（约 -72.30 亿）")
chk(abs(abs(fv) / realized - D("7.51")) < D("0.01"), f"浮亏约已实现 {abs(fv)/realized:.2f} 倍")
nav_total = D("9468449672.16") + D("3744695556.30")
chk(nav_total == D("13213145228.46"), "两类期末净值合计约 132.13 亿")
chk(abs(profit / nav_total * 100 - D("-47.43")) < D("0.01"), f"本期利润约当期末净值 {profit/nav_total*100:.2f}%")

print("第8组 仓位与行业")
chk(abs(D("11826682131.19") / D("13266792291.71") * 100 - D("89.15")) < D("0.01"), "权益占总资产 89.15% 与印刷一致")
chk(abs(D("11752158079.85") / D("11826682131.19") * 100 - D("99.37")) < D("0.01"), f"制造业约占股票仓位 {D('11752158079.85')/D('11826682131.19')*100:.2f}%")
ind = D("88.94") + D("0.56") + D("0.01")
chk(ind == D("89.51"), "境内行业三行非零合计 89.51% 与权益占净值互证")

print("第9组 前十大")
top10 = [D(x) for x in ["8.85", "7.12", "7.01", "6.77", "6.42", "4.40", "3.64", "3.41", "3.18", "2.47"]]
chk(sum(top10) == D("53.27"), f"前十大逐行合计 {sum(top10)}%")
chk(abs(top10[0] / sum(top10) * 100 - D("16.61")) < D("0.01"), "第一名约占前十大 16.61%")
chk(abs(sum(top10[:3]) - D("22.98")) < D("0.01"), "前三名合计 22.98%（源杰科技/中际旭创/新易盛）")

print("第10组 份额对平（A/C 分开）")
a0, a_sub, a_red, a1 = D("4482986809.17"), D("969810895.35"), D("1529395903.07"), D("3923401801.45")
c0, c_sub, c_red, c1 = D("1060580904.62"), D("1238084705.40"), D("740365722.77"), D("1558299887.25")
chk(a0 + a_sub - a_red == a1, "A 类份额对平")
chk(c0 + c_sub - c_red == c1, "C 类份额对平")
chk(abs((a1 - a0) / a0 * 100 - D("-12.48")) < D("0.01"), f"A 类净减 {(a1-a0)/a0*100:.2f}%")
chk(abs((c1 - c0) / c0 * 100 - D("46.93")) < D("0.01"), f"C 类净增 {(c1-c0)/c0*100:.2f}%")
t0, t1 = a0 + c0, a1 + c1
chk(t1 == D("5481701688.70"), "期末总份额与 §2 印刷 5,481,701,688.70 份一致")
chk(abs((t1 - t0) / t0 * 100 - D("-1.12")) < D("0.01"), f"总份额净减 {(t1-t0)/t0*100:.2f}%")
chk(c_sub > c0, "C 类单季申购大于其期初份额（只登记）")

print("第11组 波动与 C 类口径")
chk(abs(D("4.25") / D("1.23") - D("3.46")) < D("0.01"), "三季度标准差约为基准 3.46 倍")
chk(D("-32.93") - bench_q3 == D("-21.15"), "C 类三季度超额 -21.15 与印刷一致")
chk(abs(D("70.27") - D("-3.69") - D("73.96")) < D("0.001"), "C 类自其成立超额 73.96 与印刷一致（窗口不同于 A 类自成立）")

print("第12组 净值口径登记与管理人固有资金")
chk(abs(D("2028.90") / 100 + 1 - D("21.2890")) < D("0.0001"), "自成立增长率因子 21.2890")
chk(D("5.491") != D("21.2890"), "A 类累计净值 5.491 元与增长率因子 21.2890 并存、口径不同只登记")
chk(abs(D("2133000") / t1 * 100 - D("0.04")) < D("0.005"), "管理人固有资金 213.30 万份约占总份额 0.04% 与印刷一致")

print(f"\n全部通过：{ok} 项断言")
