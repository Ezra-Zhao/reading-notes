#!/usr/bin/env python3
"""98 Nygren（Oakmark Select OAKLX）验算脚本：十二组断言。
数据源：Oakmark Select Fund 资料单（截至 2026-09-30，Harris | Oakmark 官方 PDF）
＋ Vanguard 资料单（截至 2025-12-31，Investor Class 日历年回报与标普对照）。
全部用 Decimal 精确验算；天数用 datetime.date 差；年化滚算用浮点近似并留容差。"""
from decimal import Decimal as D, getcontext
from datetime import date

getcontext().prec = 28
ok = 0

def chk(name, cond):
    global ok
    assert cond, f"FAIL: {name}"
    ok += 1
    print(f"  ok {name}")

# 1 基金生命：1996-11-01 成立至 2026-09-30
d = (date(2026, 9, 30) - date(1996, 11, 1)).days
chk("1a 基金生命10925天", d == 10925)
chk("1b 约29.91年", abs(D(d) / D("365.25") - D("29.91")) < D("0.01"))

# 2 2026 年内劈段：YTD 与 QTD 反推上半年
chk("2a 上半年基金约+0.65%", abs((D("1.1222") / D("1.1150") - 1) * 100 - D("0.65")) < D("0.01"))
chk("2b 上半年标普约+10.22%", abs((D("1.1275") / D("1.0230") - 1) * 100 - D("10.22")) < D("0.01"))
chk("2c 上半年Russell约+16.24%", abs((D("1.1927") / D("1.0261") - 1) * 100 - D("16.24")) < D("0.01"))
chk("2d 三季度超额对标普+9.20pp", D("11.50") - D("2.30") == D("9.20"))
chk("2e 三季度超额对Russell+8.89pp", D("11.50") - D("2.61") == D("8.89"))

# 3 窗口超额：基金减标普 / 减 Russell（印刷年化）
sp = {"qtd": "2.30", "ytd": "12.75", "1y": "15.74", "3y": "22.89", "5y": "13.79", "10y": "15.33", "si": "10.27"}
ru = {"qtd": "2.61", "ytd": "19.27", "1y": "23.81", "3y": "20.07", "5y": "11.92", "10y": "11.43", "si": "9.36"}
fd = {"qtd": "11.50", "ytd": "12.22", "1y": "21.67", "3y": "18.82", "5y": "10.84", "10y": "11.39", "si": "12.08"}
chk("3a 对标普超额逐项", all(abs((D(fd[k]) - D(sp[k])) - e) < D("0.001") for k, e in
    [("qtd", D("9.20")), ("ytd", D("-0.53")), ("1y", D("5.93")), ("3y", D("-4.07")),
     ("5y", D("-2.95")), ("10y", D("-3.94")), ("si", D("1.81"))]))
chk("3b 对Russell超额逐项", all(abs((D(fd[k]) - D(ru[k])) - e) < D("0.001") for k, e in
    [("qtd", D("8.89")), ("ytd", D("-7.05")), ("1y", D("-2.14")), ("3y", D("-1.25")),
     ("5y", D("-1.08")), ("10y", D("-0.04")), ("si", D("2.72"))]))

# 4 自成立终点换算（29.91 年近似滚算，容差 1.5%）
yrs = 10925 / 365.25
chk("4a 基金一万美元终点约302996", abs(10000 * 1.1208 ** yrs - 302996) / 302996 < 0.015)
chk("4b 标普终点约186184", abs(10000 * 1.1027 ** yrs - 186184) / 186184 < 0.015)
chk("4c Russell终点约145311", abs(10000 * 1.0936 ** yrs - 145311) / 145311 < 0.015)
chk("4d 基金终点约标普1.63倍", abs((1.1208 ** yrs) / (1.1027 ** yrs) - 1.63) < 0.02)

# 5 日历年 2017-2025（Investor Class 对标普，Vanguard 2025-12-31 资料单）
cal_f = [D(x) for x in ["15.72", "-24.88", "27.69", "10.76", "34.04", "-22.74", "43.00", "14.15", "14.26"]]
cal_s = [D(x) for x in ["21.83", "-4.38", "31.49", "18.40", "28.71", "-18.11", "26.29", "25.02", "17.88"]]
def comp(rs):
    p = D(1)
    for r in rs:
        p *= 1 + r / 100
    return (p - 1) * 100
chk("5a 九年连乘基金约+137.46%", abs(comp(cal_f) - D("137.46")) < D("0.01"))
chk("5b 九年连乘标普约+255.78%", abs(comp(cal_s) - D("255.78")) < D("0.01"))
chk("5c 九年只赢标普两年", sum(1 for a, b in zip(cal_f, cal_s) if a > b) == 2)
chk("5d 九年只有两个负年份", sum(1 for a in cal_f if a < 0) == 2)

# 6 2018 年大跌与回本价
chk("6a 2018回本价约+33.12%", abs((1 / D("0.7512") - 1) * 100 - D("33.12")) < D("0.01"))
chk("6b 2018标普回本价约+4.58%", abs((1 / D("0.9562") - 1) * 100 - D("4.58")) < D("0.01"))
chk("6c 2018单年输标普20.50pp", D("-4.38") - D("-24.88") == D("20.50"))

# 7 2022-2023 两年连乘与 2023-2025 三年连乘
chk("7a 2022至2023基金约+10.48%", abs((D("0.7726") * D("1.4300") - 1) * 100 - D("10.48")) < D("0.01"))
chk("7b 2022至2023标普约+3.42%", abs((D("0.8189") * D("1.2629") - 1) * 100 - D("3.42")) < D("0.01"))
chk("7c 2023至2025基金约+86.51%", abs(comp(cal_f[6:]) - D("86.51")) < D("0.01"))
chk("7d 2023至2025标普约+86.12%", abs(comp(cal_s[6:]) - D("86.12")) < D("0.01"))

# 8 长窗拆段：五至十年前一段（年化反推）
seg_f = ((1.1139 ** 10 / 1.1084 ** 5) ** 0.2 - 1) * 100
seg_s = ((1.1533 ** 10 / 1.1379 ** 5) ** 0.2 - 1) * 100
chk("8a 五至十年前基金年化约+11.94%", abs(seg_f - 11.94) < 0.01)
chk("8b 五至十年标普年化约+16.89%", abs(seg_s - 16.89) < 0.01)

# 9 三至五年前一段：五年年化与三年年化对拆
seg35 = ((1.1084 ** 5 / 1.1882 ** 3) ** 0.5 - 1) * 100
chk("9 三至五年前一段年化约-0.14%", abs(seg35 - (-0.14)) < 0.01)

# 10 前十大合计与结构
tops = [D(x) for x in ["7.4", "6.3", "6.2", "5.7", "5.5", "5.0", "4.9", "4.9", "4.8", "4.4"]]
chk("10a 前十大合计55.10%", sum(tops) == D("55.10"))
chk("10b 前三席合计19.90%", sum(tops[:3]) == D("19.90"))
chk("10c 第一名约占前十大13.43%", abs(tops[0] / sum(tops) * 100 - D("13.43")) < D("0.01"))

# 11 组合形状：市值比、换手隐含持有期、主动份额补数
chk("11a 加权平均市值约中位数8.30倍", abs(D("355.1") / D("42.8") - D("8.30")) < D("0.01"))
chk("11b 换手58%隐含持有约1.72年", abs(1 / 0.58 - 1.72) < 0.01)
chk("11c 主动份额93.1补数6.9", D("100") - D("93.1") == D("6.9"))

# 12 类别费用差：Investor 1.00 对 R6 0.73；自成立年化差
chk("12a 费用差0.27pp", D("1.00") - D("0.73") == D("0.27"))
chk("12b R6与Investor自成立年化同为12.16对12.08差0.08pp", D("12.16") - D("12.08") == D("0.08"))

print(f"ALL {ok} assertions passed (12 groups)")
