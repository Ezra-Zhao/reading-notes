chk("10a A类净减34126617.10份约-5.80%", a1 - a0 == D("-34126617.10") and abs((a1 / a0 - 1) * 100 - D("-5.80")) < D("0.01"))
chk("10b C类净减3116561.72份约-2.51%", c1 - c0 == D("-3116561.72") and abs((c1 / c0 - 1) * 100 - D("-2.51")) < D("0.01"))
chk("10c 合计净减37243178.82份约-5.23%", (a1 + c1) - (a0 + c0) == D("-37243178.82") and abs(((a1 + c1) / (a0 + c0) - 1) * 100 - D("-5.23")) < D("0.01"))
chk("10d 赎回约申购1.83倍", abs(D("82356409.85") / D("45113231.03") - D("1.83")) < D("0.01"))

# 11 波动：八窗基金波动全高于基准
vol = [("1.10", "0.96"), ("1.09", "0.96"), ("1.00", "0.85"), ("0.99", "0.86"),
       ("1.00", "0.84"), ("1.12", "0.88"), ("1.18", "0.87"), ("1.36", "1.00")]
chk("11a 八窗波动差逐项为正", all(D(a) - D(b) > 0 for a, b in vol))
chk("11b 波动差区间+0.13至+0.36pp", min(D(a) - D(b) for a, b in vol) == D("0.13") and max(D(a) - D(b) for a, b in vol) == D("0.36"))

# 12 类别差与期末份额对平
chk("12a A与C三季度差0.16pp", D("9.37") - D("9.21") == D("0.16"))
chk("12b 期末两类份额合计675537210.66份", a1 + c1 == D("675537210.66"))
chk("12c C类二季度单季反推约-14.04%", abs((D("0.9388") / D("1.0921") - 1) * 100 - D("-14.04")) < D("0.01"))

print(f"ALL {ok} assertions passed (12 groups)")
