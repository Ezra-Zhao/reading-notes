#!/usr/bin/env python3
"""101 杨金金（交银趋势混合 519702）验算脚本：十二组断言。
数据源：交银施罗德趋势优先混合型证券投资基金 2026 年第 3 季度报告
（报告期 2026-07-01 至 2026-09-30，2026-10-27 送出，巨潮资讯原文 PDF 全 13 页）。
全部用 Decimal 精确验算；天数用 datetime.date 差；年化滚算用浮点近似并留容差。"""
from decimal import Decimal as D, getcontext
from datetime import date

getcontext().prec = 28
ok = 0

def chk(name, cond):
    global ok
    assert cond, f"FAIL: {name}"
    ok += 1
    print(f"  ok {name}")

# 1 任期与基金生命：合同生效 2010-12-22；杨金金 2020-05-06 起任
life = (date(2026, 9, 30) - date(2010, 12, 22)).days
tenure = (date(2026, 9, 30) - date(2020, 5, 6)).days
pre = (date(2020, 5, 6) - date(2010, 12, 22)).days
chk("1a 基金生命5761天", life == 5761)
chk("1b 任期2338天", tenure == 2338)
chk("1c 上任前3423天", pre == 3423 and life - tenure == pre)
chk("1d 任期约6.40年占生命约40.58%", abs(D(tenure) / D("365.25") - D("6.40")) < D("0.01") and abs(D(tenure) / D(life) * 100 - D("40.58")) < D("0.01"))

# 2 2026 年内劈段：六个月与三季度反推二季度（A 类）
chk("2a 二季度基金约-13.91%", abs((D("0.9416") / D("1.0937") - 1) * 100 - D("-13.91")) < D("0.01"))
chk("2b 二季度基准约+9.22%", abs((D("0.9919") / D("0.9082") - 1) * 100 - D("9.22")) < D("0.01"))
chk("2c 三季度超额+18.55pp", D("9.37") - D("-9.18") == D("18.55"))
chk("2d 二季度超额约-23.12pp", abs(((D("0.9416") / D("1.0937") - 1) * 100) - ((D("0.9919") / D("0.9082") - 1) * 100) - D("-23.12")) < D("0.01"))
chk("2e 二季度回本价约+16.15%", abs((D("1") / (D("0.9416") / D("1.0937")) - 1) * 100 - D("16.15")) < D("0.01"))

# 3 窗口超额逐项（A 类，印刷行）
rows = [("9.37", "-9.18", "18.55"), ("-5.84", "-0.81", "-5.03"), ("1.92", "-3.46", "5.38"),
        ("23.24", "18.04", "5.20"), ("27.44", "-1.64", "29.08"), ("240.42", "21.42", "219.00"),
        ("365.97", "41.53", "324.44"), ("681.72", "57.03", "624.69")]
chk("3 窗口超额八行逐项", all(D(a) - D(b) == D(c) for a, b, c in rows))

# 4 自生效因子与期末净值只登记比值；十年与七年、五年机械年化
chk("4a 自生效因子7.8172与净值5.0612比值约1.5445", abs(D("7.8172") / D("5.0612") - D("1.5445")) < D("0.001"))
chk("4b 十年基金年化约16.64%", abs((4.6597 ** 0.1 - 1) * 100 - 16.64) < 0.01)
chk("4c 十年基准年化约3.53%", abs((1.4153 ** 0.1 - 1) * 100 - 3.53) < 0.01)
chk("4d 七年基金年化约19.12%", abs((3.4042 ** (1 / 7) - 1) * 100 - 19.12) < 0.01)
chk("4e 五年基金年化约4.97%", abs((1.2744 ** 0.2 - 1) * 100 - 4.97) < 0.01)

# 5 长窗拆段
chk("5a 五至十年前一段约+265.64%", abs((D("4.6597") / D("1.2744") - 1) * 100 - D("265.64")) < D("0.01"))
chk("5b 五至七年前一段约+167.12%", abs((D("3.4042") / D("1.2744") - 1) * 100 - D("167.12")) < D("0.01"))
chk("5c 三至五年前一段约+3.41%", abs((D("1.2744") / D("1.2324") - 1) * 100 - D("3.41")) < D("0.01"))
chk("5d 七至十年前一段约+36.88%", abs((D("4.6597") / D("3.4042") - 1) * 100 - D("36.88")) < D("0.01"))

# 6 三季度已实现与利润：两类合计与浮盈腿
ra, pa = D("18683861.42"), D("252106697.70")
rc, pc = D("3285833.33"), D("49893552.94")
chk("6a 两类已实现合计21969694.75元", ra + rc == D("21969694.75"))
chk("6b 两类利润合计302000250.64元", pa + pc == D("302000250.64"))
chk("6c 浮盈约+280030555.89元", (pa + pc) - (ra + rc) == D("280030555.89"))
chk("6d 浮盈约已实现12.75倍", abs(D("280030555.89") / D("21969694.75") - D("12.75")) < D("0.01"))

# 7 资产形状：权益占净值、现金占总资产、债券占净值
nav = D("2806946199.63") + D("593802696.49")
chk("7a 期末净资产合计3400748896.12元", nav == D("3400748896.12"))
chk("7b 权益占净值约65.84%", abs(D("2239147867.64") / nav * 100 - D("65.84")) < D("0.01"))
chk("7c 现金占总资产28.90%印刷行", abs(D("985870037.01") / D("3411850760.95") * 100 - D("28.90")) < D("0.01"))
chk("7d 债券占净值约5.41%", abs(D("184100582.98") / nav * 100 - D("5.41")) < D("0.01"))

# 8 行业：制造业约占股票仓位；各行相加与印刷合计尾差
chk("8a 制造业约占股票仓位65.31%", abs(D("43.00") / D("65.84") * 100 - D("65.31")) < D("0.01"))
inds = [D(x) for x in ["1.52", "6.89", "43.00", "0.33", "0.38", "7.46", "0.01", "2.88", "1.38", "0.57", "1.41"]]
chk("8b 行业各行相加65.83与印刷合计65.84差0.01尾差", sum(inds) == D("65.83") and D("65.84") - sum(inds) == D("0.01"))

# 9 前十大合计与结构
tops = [D(x) for x in ["9.13", "4.02", "3.38", "1.94", "1.88", "1.87", "1.82", "1.42", "1.41", "1.39"]]
chk("9a 前十大合计28.26%", sum(tops) == D("28.26"))
chk("9b 第一名约占前十大32.31%", abs(tops[0] / sum(tops) * 100 - D("32.31")) < D("0.01"))
chk("9c 前十大约占股票仓位42.92%", abs(sum(tops) / D("65.84") * 100 - D("42.92")) < D("0.01"))

# 10 份额变动：涨的季度也在净赎回
a0, a1 = D("588723032.68"), D("554596415.58")
