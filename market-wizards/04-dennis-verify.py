"""Market Wizards 04 Dennis / 海龟实验验证脚本（clean-room 自写）
验本篇六笔可复算的账，数字均取篇内陈述，不冒充审计或实测：
1) 400 美元到约 2 亿美元是 500,000 倍；
2) 500,000 倍按 18 年折算年复合约 107.3%；
3) 海龟年均 80% 连跑 4 年是约 10.50 倍（累计约 949.8%）；
4) 1 个单位 1N 波动等于账户 1%，止损 2N 即单单位风险约 2%，单市场满仓 4 单位同向止损约 8%；
5) 金字塔加仓：入场 100、N=2、每涨 0.5N（即 1）加 1 单位，四单位均价 101.5；
6) 回撤缩仓规则：每回撤 10% 缩仓 20%，连吃两次即 0.8 的平方等于 0.64；总利润 1.75 亿摊到 23 人约人均 761 万（只作量级）。
"""

# 1
assert 200_000_000 / 400 == 500_000
print("1 通过：2 亿 / 400 = 500,000 倍")

# 2
cagr = (200_000_000 / 400) ** (1 / 18) - 1
assert round(cagr * 100, 1) == 107.3
print("2 通过：500,000 倍 / 18 年，年复合约 107.3%")

# 3
assert round(1.8 ** 4, 2) == 10.50
assert round((1.8 ** 4 - 1) * 100, 1) == 949.8
print("3 通过：年均 80% 跑 4 年约 10.50 倍，累计约 949.8%")

# 4
assert 1 * 2 == 2
assert 2 * 4 == 8
print("4 通过：1N=1%，2N 止损=单单位约 2%，4 单位约 8%")

# 5
entries = [100, 101, 102, 103]
assert sum(entries) / len(entries) == 101.5
print("5 通过：100/101/102/103 四单位均价 101.5")

# 6
assert round(0.8 ** 2, 2) == 0.64
assert round(175_000_000 / 23 / 1_000_000, 2) == 7.61
print("6 通过：两次缩仓后剩 64%；1.75 亿 / 23 人约人均 761 万")

print("全部六项断言通过")
