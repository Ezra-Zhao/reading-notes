#!/usr/bin/env python3
"""102 Herro（Oakmark International OAKIX）验算脚本：十二组断言。
数据源：Oakmark International Fund Quarterly Commentary, September 30, 2026
（oakmark.com 官方 PDF，第三季度 2026，业绩表与持仓权重均出此文件；
基金页面补充：前十大合计 28.1%、持仓 59 只、管理资产 11,719.86 百万美元）。
全部用 Decimal 精确验算；天数用 datetime.date 差；年化滚算用浮点近似并留容差。"""
from decimal import Decimal as D, getcontext
from datetime import date

getcontext().prec = 28
ok = 0

def chk(name, cond):
    global ok
    assert cond, f"FAIL: {name}"
    ok += 1
    print(f"  ok {name}")

# 1 基金生命与经理：成立 1992-09-30；Herro 栏注 (1992)，与成立同年
life = (date(2026, 9, 30) - date(1992, 9, 30)).days
chk("1a 基金生命12418天", life == 12418)
chk("1b 基金生命约34.00年", abs(D(life) / D("365.25") - D("34.00")) < D("0.01"))
chk("1c 经理三人Herro首位", True)  # 资料单登记：Herro (1992)、Coniaris (1999)、Liu (2009)，认首席不认独管

# 2 2026 年内劈段：年初至 9 月 30 日与三季度反推上半年（Investor 类）
chk("2a 上半年基金约+0.95%", abs((D("1.0160") / D("1.0064") - 1) * 100 - D("0.95")) < D("0.01"))
chk("2b 上半年基准约+9.19%", abs((D("1.1016") / D("1.0089") - 1) * 100 - D("9.19")) < D("0.01"))
chk("2c 上半年价值指数约+10.85%", abs((D("1.1496") / D("1.0371") - 1) * 100 - D("10.85")) < D("0.01"))
chk("2d 上半年超额约-8.24pp", abs(((D("1.0160") / D("1.0064") - 1) - (D("1.1016") / D("1.0089") - 1)) * 100 - D("-8.24")) < D("0.01"))

# 3 窗口超额逐项（Investor 类对基准与价值指数，印刷行）
chk("3a 三季度超额-0.25pp对基准-3.07pp对价值", D("0.64") - D("0.89") == D("-0.25") and D("0.64") - D("3.71") == D("-3.07"))
chk("3b 年初至今超额-8.56pp对基准-13.36pp对价值", D("1.60") - D("10.16") == D("-8.56") and D("1.60") - D("14.96") == D("-13.36"))
chk("3c 一年超额-9.38pp对基准-17.78pp对价值", D("6.51") - D("15.89") == D("-9.38") and D("6.51") - D("24.29") == D("-17.78"))
chk("3d 年化超额三年-7.16pp五年-4.30pp十年-2.46pp自成立+1.92pp", D("11.73") - D("18.89") == D("-7.16") and D("5.36") - D("9.66") == D("-4.30") and D("6.81") - D("9.27") == D("-2.46") and D("8.69") - D("6.77") == D("1.92"))

# 4 累计窗口：三年、五年、十年连乘（年化印刷行反推）
chk("4a 三年累计基金约39.48%基准约68.05%价值约89.24%", abs((1.1173 ** 3 - 1) * 100 - 39.48) < 0.01 and abs((1.1889 ** 3 - 1) * 100 - 68.05) < 0.01 and abs((1.2369 ** 3 - 1) * 100 - 89.24) < 0.01)
chk("4b 五年累计基金约29.83%基准约58.58%价值约98.61%", abs((1.0536 ** 5 - 1) * 100 - 29.83) < 0.01 and abs((1.0966 ** 5 - 1) * 100 - 58.58) < 0.01 and abs((1.1471 ** 5 - 1) * 100 - 98.61) < 0.01)
chk("4c 十年累计基金约93.25%基准约142.67%价值约168.96%", abs((1.0681 ** 10 - 1) * 100 - 93.25) < 0.01 and abs((1.0927 ** 10 - 1) * 100 - 142.67) < 0.01 and abs((1.1040 ** 10 - 1) * 100 - 168.96) < 0.01)

# 5 自成立一万美元终点：基金约17.0万、基准约9.27万、价值约12.49万
chk("5a 自成立基金终点约169999美元", abs(10000 * 1.0869 ** 34 - 169999) < 100)
chk("5b 自成立基准终点约92742美元", abs(10000 * 1.0677 ** 34 - 92742) < 100)
chk("5c 自成立价值终点约124941美元", abs(10000 * 1.0771 ** 34 - 124941) < 100)
chk("5d 基金终点约基准1.83倍约价值1.36倍", abs((1.0869 ** 34) / (1.0677 ** 34) - 1.83) < 0.01 and abs((1.0869 ** 34) / (1.0771 ** 34) - 1.36) < 0.01)

# 6 长窗拆段：五至十年前一段与三至五年前一段
chk("6a 五至十年前一段基金约+48.85%基准约+53.02%价值约+35.42%", abs(((1.0681 ** 10) / (1.0536 ** 5) - 1) * 100 - 48.85) < 0.01 and abs(((1.0927 ** 10) / (1.0966 ** 5) - 1) * 100 - 53.02) < 0.01 and abs(((1.1040 ** 10) / (1.1471 ** 5) - 1) * 100 - 35.42) < 0.01)
chk("6b 三至五年前一段基金约-6.92%基准约-5.64%价值约+4.95%", abs(((1.0536 ** 5) / (1.1173 ** 3) - 1) * 100 - (-6.92)) < 0.01 and abs(((1.0966 ** 5) / (1.1889 ** 3) - 1) * 100 - (-5.64)) < 0.01 and abs(((1.1471 ** 5) / (1.2369 ** 3) - 1) * 100 - 4.95) < 0.01)

# 7 地区：前三区相加 83.0%，新兴市场 8.8% 为另一口径不并入
chk("7a 前三地区相加83.0%", D("62.0") + D("13.3") + D("7.7") == D("83.0"))
chk("7b 其余地区约17.0%", D("100") - D("83.0") == D("17.0"))

# 8 规模与集中度：前十大 28.1%、59 只、AUM 11719.86 百万美元
chk("8a 前十大约3293.28百万美元", abs(D("11719.86") * D("0.281") - D("3293.28")) < D("0.01"))
chk("8b SAP约351.60百万美元", abs(D("11719.86") * D("0.030") - D("351.60")) < D("0.01"))
chk("8c 前十大之外约8426.58百万美元", abs(D("11719.86") - D("11719.86") * D("0.281") - D("8426.58")) < D("0.01"))

# 9 逐名权重：点名十只相加 18.6%
names = [D(x) for x in ["3.0", "2.9", "2.8", "2.5", "2.5", "1.9", "1.4", "1.0", "0.4", "0.2"]]
chk("9a 点名十只权重相加18.6%", sum(names) == D("18.6"))
chk("9b SAP3.0%为点名第一", names[0] == D("3.0") and max(names) == D("3.0"))
chk("9c MercadoLibre0.2%为点名最小", min(names) == D("0.2"))

# 10 份额类别差：R6 对 Investor 类
chk("10a R6三季度高0.12pp年初至今高0.25pp一年高0.32pp自成立高0.08pp", D("0.76") - D("0.64") == D("0.12") and D("1.85") - D("1.60") == D("0.25") and D("6.83") - D("6.51") == D("0.32") and D("8.77") - D("8.69") == D("0.08"))
chk("10b 费用差Investor高R6约0.30pp", D("1.06") - D("0.76") == D("0.30"))

# 11 本季动作计数：贡献 3 只、拖累 3 只、新买 4 只、清仓 3 只
chk("11a 贡献3只拖累3只新买4只清仓3只", 3 + 3 + 4 + 3 == 13)

# 12 费用四档逐项
chk("12a 费用四档1.06/0.89/0.82/0.76逐降", D("1.06") > D("0.89") > D("0.82") > D("0.76"))
chk("12b Advisor比Investor低0.17pp机构比顾问低0.07pp", D("1.06") - D("0.89") == D("0.17") and D("0.89") - D("0.82") == D("0.07"))

print(f"ALL {ok} assertions passed (12 groups)")
