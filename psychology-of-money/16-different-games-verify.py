#!/usr/bin/env python3
"""《金钱心理学》第16章验算：每个人的情况不同。只复核书中数字的算术含义。"""
ok = []
def chk(name, cond):
    ok.append(cond)
    print(("PASS" if cond else "FAIL"), name)

# 1 两次泡沫的家庭财富损失：互联网6.2万亿 vs 房地产8万亿（美元）
chk("房地产损失约为互联网泡沫的1.29倍", abs(8/6.2 - 1.2903) < 0.001)
chk("两次合计蒸发14.2万亿美元", abs(6.2 + 8 - 14.2) < 1e-9)
# 2 炒房交易量：2000Q1约2万套 -> 2004Q1约10万套
chk("炒房量涨到约5倍（增加4倍多）", abs(100000/20000 - 5) < 1e-9)
# 3 泡沫破灭后回落到每季约4万套
chk("破灭后为峰值的40%、较高点跌60%", abs(40000/100000 - 0.4) < 1e-9 and abs(1 - 40000/100000 - 0.6) < 1e-9)
chk("破灭后仍是2000年水平的2倍", abs(40000/20000 - 2) < 1e-9)
# 4 思科1999年涨300%到60美元：涨300%即变为原来的4倍
chk("思科涨前价格约15美元", abs(60/4 - 15) < 1e-9)
# 5 思科估值6000亿美元、股价60美元 -> 隐含股数约100亿股
chk("思科隐含股数约100亿股", abs(6000/60 - 100) < 1e-9)
# 6 共同基金年换手率120% -> 平均持有期约10个月
chk("120%换手率对应平均持有约10个月", abs(12/1.2 - 10) < 1e-9)
# 7 雅虎5美元 vs 500美元：相差100倍，日内交易者只关心方向
chk("雅虎两个价格相差100倍", abs(500/5 - 100) < 1e-9)
print(f"{sum(ok)}/{len(ok)} assertions passed")
assert all(ok)
