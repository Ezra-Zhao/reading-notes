#!/usr/bin/env python3
"""《金钱心理学》第 02 篇验证脚本：核查第 2 章「运气与风险」中可算的数字命题。

核查对象（书中数字与公开常数，本脚本只验算术一致性）：
1. 百万分之一的漏斗：1968 年全世界高中年龄人口约 3.03 亿（联合国口径，
   书中数），其中只有约 300 人就读于湖滨学校（Lakeside School）。
   303,000,000 / 300 = 1,010,000，与书中「百万分之一」应在 2% 误差内。
2. 漏斗逐级收缩：3.03 亿（全球）-> 1,800 万（美国）-> 27 万（华盛顿州）
   -> 约 10 万（西雅图地区）-> 300（湖滨），每一级都应严格变小，且
   美国占全球约 5.9%、华盛顿州占美国 1.5%。
3. 母亲俱乐部那 3,000 美元：1968 年湖滨学校母亲俱乐部用义卖所得约
   3,000 美元租下接入 GE 主机的电传打字机。用 BLS CPI-U 年均值
   （1968 年 34.8、2020 年 258.8）换算，约合 2020 年 22,310 美元——
   即这笔钱在当年不是小钱，落在 22,000-22,600 区间。
4. 肯特·埃文斯的年龄线：1968 年盖茨 13 岁、两人八年级同班；埃文斯
   1972 年登山事故去世、年 17 岁。1968->1972 共 4 年，13+4=17，
   两条线自洽。微软创立于 1975 年，去世距创立 3 年。
5. 登山死亡的量级：书中说美国每年约三十几起（three dozen = 36）
   登山死亡。36 / 18,000,000（1968 年美国高中年龄人口）约等于
   五十万分之一每年——与书中「高中时期死于登山的概率约百万分之一」
   只在同量级（书中为作者粗估口径，本脚本只验量级、不当精算结论）。

纯标准库，无外部数据文件。断言失败即退出码非零。
"""

# 1. 百万分之一漏斗的终点
world = 303_000_000
lakeside = 300
odds = world / lakeside
assert abs(odds - 1_000_000) / 1_000_000 < 0.02, odds
print(f"[1] 303,000,000 / 300 = {odds:,.0f}，与「百万分之一」误差 1.0% 内 OK")

# 2. 漏斗逐级收缩
us, wa, seattle = 18_000_000, 270_000, 100_000
assert world > us > wa > seattle > lakeside
us_share = us / world
wa_share = wa / us
assert 0.055 < us_share < 0.065, us_share
assert wa_share == 0.015, wa_share
print(f"[2] 漏斗单调收缩；美国占全球 {us_share:.1%}、华盛顿州占美国 {wa_share:.1%} OK")

# 3. 3,000 美元（1968）的通胀换算（BLS CPI-U 年均：1968=34.8，2020=258.8）
cpi_1968, cpi_2020 = 34.8, 258.8
converted = 3000 * cpi_2020 / cpi_1968
assert 22_000 <= converted <= 22_600, converted
print(f"[3] 3,000 美元(1968) x CPI 258.8/34.8 = {converted:,.0f} 美元(2020)，当年不是小钱 OK")

# 4. 埃文斯年龄线与微软创立间隔
assert 1972 - 1968 == 4 and 13 + 4 == 17
assert 1975 - 1972 == 3
print("[4] 1968 年 13 岁 -> 1972 年 17 岁自洽；去世距微软创立（1975）3 年 OK")

# 5. 登山死亡量级（书中 three dozen 与作者粗估，只验量级）
deaths_per_year = 36
per_year_odds = deaths_per_year / us
assert 1 / 1_000_000 < per_year_odds < 1 / 100_000, per_year_odds
print(f"[5] 36 / 18,000,000 = {per_year_odds:.2e}/年（约五十万分之一），与书中百万分之一同量级 OK")

print("ALL CHECKS PASSED")
