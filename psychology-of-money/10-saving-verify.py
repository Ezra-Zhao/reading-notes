# 1 能效账：每 1 美元 GDP 的能耗比 1950 年减少 60%，即只剩 40%
intensity_1950 = 1.00
intensity_now = intensity_1950 * (1 - 0.60)
assert abs(intensity_now - 0.40) < 1e-9
# 2 油耗对照：全车队平均油耗里程约为 1975 年的 2 倍；
#    1989 年福特金牛 18 英里/加仑，2019 年雪佛兰 Suburban 18.1 英里/加仑，
#    大型 SUV 已追平当年的普通轿车，差值只有 0.1
assert abs(18.1 - 18.0 - 0.1) < 1e-9
fleet_ratio = 2.0
assert fleet_ratio == 2
# 3 供给 vs 效率：1975 年以来美国油气产量增加 65%（系数 1.65），
#    而单位能耗换来的产出翻了 1 倍还多（系数 >2）——效率的贡献大于供给
assert 1 + 0.65 == 1.65 and 2.0 > 1.65
# 4 储蓄率恒等式：财富 = 收入 - 开支的积累；收入相同，储蓄率 30% vs 5%，
#    10 年存量差 = 年收入 x 0.25 x 10
income, years = 100_000, 10
assert income * 0.30 * years - income * 0.05 * years == 250_000
# 5 回报率对照（书中设例）：同一净值，甲回报 8%、支出为乙的一半；
#    设两人各有 100 万、乙年支出 8 万、甲年支出 4 万：
#    甲年净增 = 8% x 100万 - 4万 = +4万；乙年净增 = 12% x 100万 - 8万 = +4万
#    回报低 4 个百分点，靠支出减半打平——欲望与所得的落差可以抵回报差
principal = 1_000_000
net_a = principal * 0.08 - 40_000
net_b = principal * 0.12 - 80_000
assert net_a == net_b == 40_000
# 6 精力错配：专业人士每周 80 小时研究，只为多争 0.1 个百分点回报；
#    普通人经济生活中却有 2-3 个百分点的浮动空间——空间是目标增量的 20-30 倍
assert 2.0 / 0.1 == 20 and 3.0 / 0.1 == 30
# 7 无目标储蓄的期权价值（自设情景）：存款够覆盖 6 个月开支，
#    就能等 6 个月再接工作；覆盖 0 个月时只能立刻接受任何机会
monthly_cost = 5_000
assert monthly_cost * 6 == 30_000 and monthly_cost * 0 == 0
# 8 全球竞争计数（书中转述）：SAT 满分约 600 人、距满分几分之内约 7,000 人，
#    后者约为前者的 11.7 倍——聪明人从来不稀缺
assert abs(7000 / 600 - 11.6667) < 0.01
# 9 旧世界对照（书中引戈登记录）：100 多年前 75% 的美国人没有电话、
#    也没有常规邮政服务，即只有 25% 的人处在可远程竞争的网络里
assert 100 - 75 == 25
print("all 9 assertions passed")
