#!/usr/bin/env python3
"""《金钱心理学》第17章验算：悲观主义的诱惑。只复核书中数字的算术含义。"""
ok = []
def chk(name, cond):
    ok.append(cond)
    print(("PASS" if cond else "FAIL"), name)

# 1 1946年日本人均每天摄入热量不足800大卡，低于成人日需约2000大卡的四成
chk("800大卡不足2000大卡日需的40%", 800/2000 <= 0.4)
# 2 战后日本经济增长近14倍、寿命几乎翻一番（定性对照：14倍即增长1300%）
chk("增长14倍等于净增1300%", abs((14-1)*100 - 1300) < 1e-9)
# 3 过去一个世纪股市市值连股息增长约1.7万倍 -> 年化约10.2%
chk("1.7万倍/100年年化约10.2%", abs((17000**(1/100)-1) - 0.1024) < 0.001)
# 4 1929年崩盘前夕只有2.5%的美国人持股 -> 97.5%是旁观者
chk("持股2.5%意味着97.5%未持股", abs(100-2.5 - 97.5) < 1e-9)
# 5 油价2001年20美元 -> 2008年138美元
chk("油价涨到原来的6.9倍", abs(138/20 - 6.9) < 1e-9)
# 6 布朗断言世界日产上限8500万桶，实际超过1亿桶
chk("实际产量超断言上限约17.6%", abs(10000/8500-1 - 0.1765) < 0.001)
# 7 美国日产量500万桶 -> 1300万桶
chk("美国产量变为2.6倍、净增160%", abs(1300/500 - 2.6) < 1e-9 and abs((1300-500)/500 - 1.6) < 1e-9)
# 8 耶金：美国储量86%来自修正估算 -> 初始估算只占14%
chk("初始估算占比14%", abs(100-86 - 14) < 1e-9)
# 9 心脏病死亡率下降70%以上 -> 降到原来的30%以下
chk("降70%后剩余约三成", abs((1-0.70) - 0.30) < 1e-9)
# 10 每周5次卡特里娜（每次逾1800人死亡）一年总死亡 vs 每年挽救约50万人
chk("每周5次卡特里娜一年46.8万人仍少于50万", 5*52*1800 == 468000 and 468000 < 500000)
# 11 股市6年涨140% -> 年化约15.7%
chk("6年涨140%年化约15.7%", abs((2.4**(1/6)-1) - 0.157) < 0.002)
print(f"{sum(ok)}/{len(ok)} assertions passed")
assert all(ok)
