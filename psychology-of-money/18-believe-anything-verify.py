#!/usr/bin/env python3
"""《金钱心理学》第18章验算：当你相信一切的时候。只复核书中数字的算术含义。"""
ok = []
def chk(name, cond):
    ok.append(cond)
    print(("PASS" if cond else "FAIL"), name)

# 1 2007-2009美国家庭财富缩水16万亿美元（量级对照：约为当时美国一年GDP的量级）
chk("财富缩水16万亿为万亿量级", 16_000_000_000_000 == 16 * 10**12)
# 2 股市市值只有两年前的一半 -> 跌幅50%
chk("市值减半等于跌50%", abs((0.5 - 1) * 100 + 50) < 1e-9)
# 3 主动型基金85%跑输基准 -> 只有15%跑赢
chk("跑输85%意味着跑赢仅15%", abs(100 - 85 - 15) < 1e-9)
# 4 主动型基金吸引近5万亿美元（与85%跑输并存，靠的是故事不是业绩）
chk("5万亿美元量级核对", 5 * 10**12 == 5_000_000_000_000)
# 5 美联储2007年预测2008-2009增速最低1.6%，实际萎缩逾2% -> 摆幅至少3.6个百分点
chk("预测下限与实际摆幅至少3.6个百分点", abs(1.6 - (-2.0) - 3.6) < 1e-9)
# 6 预测区间1.6%-2.8%中点2.2%，与实际-2%相差4.2个百分点
chk("预测中点与实际差4.2个百分点", abs((1.6 + 2.8) / 2 - (-2.0) - 4.2) < 1e-9)
# 7 1918年停战，21年后二战爆发 -> 1939年
chk("1918+21=1939", 1918 + 21 == 1939)
# 8 伦敦大瘟疫18个月夺去四分之一人口 -> 死亡占比25%
chk("四分之一等于25%", abs(1 / 4 * 100 - 25) < 1e-9)
# 9 新视野号9.5年旅程只比预计早约1分钟 -> 误差占比约0.00002%，准确率约99.99998%
mins = 9.5 * 365.25 * 24 * 60
chk("1分钟误差占比约0.00002%", abs(1 / mins * 100 - 0.00002) < 0.000005)
chk("准确率约99.99998%", abs((1 - 1 / mins) * 100 - 99.99998) < 0.000005)
# 10 卡尼曼问创业者：成绩多大程度取决于自身？无人低于80% -> 外部因素自评上限20%
chk("自评自身贡献不低于80%意味着外部至多20%", abs(100 - 80 - 20) < 1e-9)
print(f"{sum(ok)}/{len(ok)} assertions passed")
assert all(ok)
