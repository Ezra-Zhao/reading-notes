#!/usr/bin/env python3
# 《金钱心理学》第20章「我的理财方案」拆书验算脚本（自写，断言均为本篇用到的算术与计数）
checks = []
def chk(name, cond):
    checks.append((name, cond))
    print(("PASS " if cond else "FAIL ") + name)

# 1 晨星口径：组合经理约一半不买自管基金
chk("一半等于50%", 1/2 == 0.50)
# 2 父亲40岁成医、约20年后辞职 -> 约60岁
chk("40岁成医加20年约60岁", 40 + 20 == 60)
# 3 现金约占金融资产20% -> 投资部分约80%
chk("现金20%则投资80%", 100 - 20 == 80)
# 4 现金拖累演示：80%年化5%+20%年化0% -> 组合4.0%
chk("八二配比混合收益4.0%", abs(0.8*5 + 0.2*0 - 4.0) < 1e-9)
# 5 三十年复利：全仓5%约4.32倍，八二组合4%约3.24倍，差距约25%
full = 1.05**30; mix = 1.04**30
chk("全仓30年约4.32倍", abs(full - 4.32) < 0.01)
chk("八二组合30年约3.24倍", abs(mix - 3.24) < 0.01)
chk("现金拖累约吃掉四分之一终值", abs((full-mix)/full - 0.25) < 0.01)
# 6 截至2019十年间85%大盘主动基金跑输 -> 跑赢仅15%
chk("跑输85%意味着跑赢15%", 100 - 85 == 15)
# 7 20多岁时持有个股约25只（书中约数，本篇只作计数登记）
chk("个股约25只为二十量级", 20 <= 25 <= 30)
# 8 收入翻倍而支出不变的演示：收入100支出60储蓄率40% -> 收入200储蓄率70%
chk("收入翻倍支出不变储蓄率40%升至70%", (100-60)/100 == 0.40 and (200-60)/200 == 0.70)
# 9 净资产三件套：房子+支票账户+指数基金 = 3 类
chk("净资产构成恰为3类", len(["房子", "支票账户", "指数基金"]) == 3)
# 10 投资精力三要素中可控的两项：储蓄率、耐心（乐观不可控）
chk("三要素中可控项为2", len(["储蓄率", "耐心"]) == 2 and len(["储蓄率", "耐心", "乐观"]) == 3)

failed = [n for n, c in checks if not c]
print(f"{len(checks)-len(failed)}/{len(checks)} assertions passed")
raise SystemExit(1 if failed else 0)
