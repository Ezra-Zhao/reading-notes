#!/usr/bin/env python3
"""《金钱心理学》第 04 篇验证脚本：核查第 4 章「复利之谜」中可算的数字命题。

核查对象（书中数字，本脚本只验算术一致性）：
1. 巴菲特净资产结构：845 亿中 842 亿在 50 岁后、815 亿在 65 岁后赚到。
   65 岁后占比 815/845 = 96.4%；50 岁前只攒下 3 亿（845-842）。
2. 思想实验：30 岁只有 2.5 万美元、按 22% 年回报、到 60 岁退休。
   25,000 x 1.22^31 ≈ 1,190 万（书中数字对应 31 个复利年头，含起止年
   口径）；与 845 亿相比只剩约 0.014%，即少了约 99.99%——书中
   「少了 99.9%」为约数口径，本脚本按数量级核。
3. 西蒙斯对照：66% 是 22% 的整 3 倍；其净资产 210 亿是巴菲特
   845 亿的 24.9%，与书中「25%」一致。
4. 西蒙斯假想：若按 66% 复利 70 年，1.66^70 ≈ 3.8e15——倍数本身
   已是千万亿量级，书中给出的天文数字（约 6.39e19 美元）量级自洽
   本金恰与思想实验同一笔 2.5 万美元——本脚本核到原值口径。
5. 线性 vs 指数的心算例子：8 加 9 次 = 72；8 连乘 9 次 = 134,217,728，
   两者相差约 186 万倍——书中「脑袋要爆炸」的算术注脚。
6. 硬盘增长：1950 年代首块硬盘 3.5M；100T = 100 x 1024 x 1024 M
   = 104,857,600M，与书中「增加了 100,000,000M」在 5% 内；
   100T 相对 3.5M 约为 2,996 万倍，与书中「3,000 万倍」一致。

纯标准库，无外部数据文件。断言失败即退出码非零。
"""

# 1. 巴菲特净资产的时间结构
total, after50, after65 = 84.5, 84.2, 81.5  # 单位：十亿美元
assert abs(after65 / total - 0.9645) < 0.001
assert abs((total - after50) - 0.3) < 1e-9
print(f"[1] 65 岁后占比 {after65/total*100:.1f}%；50 岁前攒下 {(total-after50)*10:.0f} 亿美元（845-842）OK")

# 2. 思想实验：2.5 万、22%、约 31 个复利年头
hypo = 25_000 * 1.22 ** 31
assert abs(hypo - 11_900_000) / 11_900_000 < 0.01, hypo
share = hypo / 84_500_000_000
assert share < 0.0002
print(f"[2] 25,000 x 1.22^31 = {hypo:,.0f} 美元，约合书中 1,190 万；仅为 845 亿的 {share*100:.3f}% OK")

# 3. 西蒙斯对照
assert 66 / 22 == 3
assert abs(21 / 84.5 - 0.25) < 0.005
print(f"[3] 66% / 22% = 3.0 倍；210 / 845 = {21/84.5*100:.1f}%，约合书中 25% OK")

# 4. 西蒙斯 70 年假想的量级
factor = 1.66 ** 70
assert 1e15 < factor < 1e16
implied = 63_900_781_780_748_160_000 / factor
assert abs(implied - 25_000) / 25_000 < 0.01
print(f"[4] 1.66^70 = {factor:.2e}；书中天文数字反推起始本金约 {implied:,.0f} 美元，与思想实验同一笔 2.5 万 OK")

# 5. 线性 vs 指数
assert 8 * 9 == 72 and 8 ** 9 == 134_217_728
print(f"[5] 8x9 = 72，8^9 = 134,217,728，相差 {8**9//72:,} 倍 OK")

# 6. 硬盘增长
hundred_t_in_m = 100 * 1024 * 1024
assert abs(hundred_t_in_m - 100_000_000) / 100_000_000 < 0.05
ratio = hundred_t_in_m / 3.5
assert 29_000_000 < ratio < 31_000_000
print(f"[6] 100T = {hundred_t_in_m:,}M，约为 1950 年代 3.5M 的 {ratio:,.0f} 倍，约合书中 3,000 万倍 OK")

print("ALL CHECKS PASSED")
