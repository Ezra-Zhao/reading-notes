#!/usr/bin/env python3
"""《金钱心理学》第 03 篇验证脚本：核查第 3 章「永不知足」中可算的数字命题。

核查对象（书中数字与公开常数，本脚本只验算术一致性）：
1. 顾磊杰的时薪：截至 2008 年身家约 1 亿美元。书中说哪怕以 5% 的年
   回报率计算，这些钱每小时都能产生接近 600 美元的收益。
   100,000,000 x 5% / (365 x 24) = 570.78 美元/小时，应落在 550-600 区间。
2. 攀比阶梯的底级：棒球新秀年薪约 50 万美元；迈克·特劳特 12 年
   4.3 亿美元合同折合每年约 3,600 万美元。430,000,000 / 12 = 35,833,333，
   与书中 3,600 万应在 1% 误差内；特劳特年薪约为新秀的 71.7 倍。
3. 攀比阶梯的顶级：贝索斯 2018 年净收入 240 亿美元，折合时薪
   24,000,000,000 / (365 x 24) = 2,739,726 美元——比那位棒球新秀
   一整年的 50 万美元还多，约为其年薪的 5.48 倍（书中原话的算术核查）。
4. 攀比阶梯全链单调递增且无一级可被下一级「追平」：50 万（新秀）
   < 3,583 万（特劳特）< 3.4 亿（2018 年收入前十对冲基金经理门槛）
   < 7.7 亿（前五门槛）< 35 亿（巴菲特 2018）< 240 亿（贝索斯 2018），
   顶层是底层的 48,000 倍——每一级向上看都隔着数量级，这正是本章
   「攀比没有天花板」的算术形态。
5. 麦道夫合法生意的体量：书中引 1992 年《华尔街日报》——麦道夫公司
   场外电子交易日均成交量 7.4 亿美元，相当于纽约证券交易所每天
   交易量的 9%。反推纽交所日均约 82.2 亿美元，7.4 / 82.2 = 9.0%，自洽。
6. 内幕交易那通电话的账：拉贾拉特南在通话后立即买入 17.5 万股高盛
   股票、消息公布后瞬间赚到约 100 万美元，折合每股约 5.71 美元的
   跳涨；SEC 口径顾磊杰的内幕消息共带来约 1,700 万美元收益，是这
   单笔 100 万的 17 倍——即书中「这只是一例」的算术注脚。

纯标准库，无外部数据文件。断言失败即退出码非零。
"""

# 1. 顾磊杰 1 亿美元按 5% 年回报的时薪
net_worth = 100_000_000
hourly = net_worth * 0.05 / (365 * 24)
assert 550 <= hourly <= 600, hourly
print(f"[1] 100,000,000 x 5% / 8760 = {hourly:,.2f} 美元/小时，接近书中「600 美元」OK")

# 2. 特劳特年薪与新秀的倍数
trout_annual = 430_000_000 / 12
rookie = 500_000
assert abs(trout_annual - 36_000_000) / 36_000_000 < 0.01, trout_annual
print(f"[2] 430,000,000 / 12 = {trout_annual:,.0f} 美元/年，与书中 3,600 万误差 0.5% 内；"
      f"为新秀年薪的 {trout_annual / rookie:.1f} 倍 OK")

# 3. 贝索斯 2018 年收入的时薪 vs 新秀年薪
bezos_hourly = 24_000_000_000 / (365 * 24)
assert bezos_hourly > rookie, bezos_hourly
print(f"[3] 24,000,000,000 / 8760 = {bezos_hourly:,.0f} 美元/小时 > 新秀年薪 500,000，"
      f"约为其 {bezos_hourly / rookie:.2f} 倍 OK")

# 4. 攀比阶梯全链
ladder = [500_000, trout_annual, 340_000_000, 770_000_000, 3_500_000_000, 24_000_000_000]
assert all(b > a for a, b in zip(ladder, ladder[1:]))
assert ladder[-1] / ladder[0] == 48_000
print(f"[4] 阶梯六级单调递增，顶/底 = {ladder[-1] / ladder[0]:,.0f} 倍，每级向上都隔着数量级 OK")

# 5. 麦道夫日均成交量占纽交所 9% 的反推
nyse_daily = 740_000_000 / 0.09
assert abs(740_000_000 / nyse_daily - 0.09) < 1e-9
print(f"[5] 740,000,000 / 9% 反推纽交所日均约 {nyse_daily:,.0f} 美元，回代占比 9.0% 自洽 OK")

# 6. 内幕交易单笔的每股跳涨与 SEC 总额倍数
per_share = 1_000_000 / 175_000
assert 5.0 <= per_share <= 6.5, per_share
assert 17_000_000 / 1_000_000 == 17
print(f"[6] 1,000,000 / 175,000 股 = 每股约 {per_share:.2f} 美元跳涨；SEC 总额 1,700 万为单笔的 17 倍 OK")

print("ALL CHECKS PASSED")
