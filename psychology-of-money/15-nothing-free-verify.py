#!/usr/bin/env python3
"""《金钱心理学》第15章验算：世上没有免费的午餐。只复核书中数字的算术含义。"""
ok = []
def chk(name, cond):
    ok.append(cond)
    print(("PASS" if cond else "FAIL"), name)

# 1 通用电气股价 2007年40美元 -> 2018年7美元
chk("GE跌幅82.5%", abs((40-7)/40 - 0.825) < 1e-9)
# 2 标普500 50年涨119倍 -> 年化约10.0%
cagr = 119 ** (1/50) - 1
chk("标普119倍年化约10%", 0.099 < cagr < 0.102)
# 3 网飞350倍 vs 魔爪319倍
chk("网飞倍数约为魔爪1.10倍", abs(350/319 - 1.097) < 0.01)
# 4 低于此前高点的时间占比：网飞94% / 魔爪95%
chk("网飞仅6%时间不在回撤区", abs(100-94 - 6) < 1e-9 and abs(100-95 - 5) < 1e-9)
# 5 战术基金 9/112 胜出
chk("战术基金胜出率约8.0%", abs(9/112 - 0.0804) < 0.001)
chk("近四分之一约28只", abs(112/4 - 28) < 1e-9)
# 6 个人投资者每年跑输所投基金0.5个百分点（自设对照：8% vs 7.5%，30年）
a = 1.08**30; b = 1.075**30
chk("0.5pp三十年终值差约15%", 0.13 < a/b - 1 < 0.17)
# 7 韦尔奇每股收益预期0.25 -> 报0.26
chk("EPS超预期4%", abs((0.26-0.25)/0.25 - 0.04) < 1e-9)
# 8 迪士尼门票100美元 vs 新车30000美元
chk("一辆新车=300张门票", abs(30000/100 - 300) < 1e-9)
# 9 道指1950-2019年均约11%（含股息）69年复利量级
chk("11%滚69年约千倍量级", 1000 < 1.11**69 < 2000)
print(f"{sum(ok)}/{len(ok)} assertions passed")
assert all(ok)
