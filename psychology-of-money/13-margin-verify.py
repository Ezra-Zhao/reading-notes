# 第13章验算：为犯错留余地——容错空间
# 只复核书中数字的算术含义与自设情景，不作独立统计引用
# 1 算牌优势约2% -> 庄家仍有约49%胜率，玩家约51%
assert abs((100 - 2) / 2 - 49) < 1e-9 and abs(51 + 49 - 100) < 1e-9
# 2 本金切100份：1万美元 -> 每注100美元；连输10手只亏10%
assert 10000 / 100 == 100 and abs(10 * 100 / 10000 - 0.10) < 1e-9
# 3 巴泽曼转述：他人翻修超支估计区间25%~50%，中点37.5%
assert abs((25 + 50) / 2 - 37.5) < 1e-9
# 4 资产跌30% -> 还剩70%
assert abs(1 - 0.30 - 0.70) < 1e-9
# 5 历史真实回报6.8%，作者预估低三分之一 -> 约4.53%
assert abs(6.8 * (1 - 1/3) - 4.5333) < 0.001
# 6 自设情景：单次成功率95%，一生重复50次至少失败一次的概率约92.3%
p = 1 - 0.95 ** 50
assert abs(p - 0.9231) < 0.001
# 7 斯大林格勒坦克：104辆中能动的不到20辆 -> 可用率<19.23%，趴窝>80%
assert abs(20 / 104 - 0.1923) < 0.001 and (104 - 20) / 104 > 0.80
# 8 盖茨现金口径：留够1年工资 = 12个月缓冲
assert 1 * 12 == 12
print("all 8 assertions passed")
