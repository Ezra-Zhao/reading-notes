#!/usr/bin/env python3
# 《金钱心理学》附录「美国消费者心态形成简史」拆书验算脚本（自写，断言均为本篇用到的算术与计数）
checks = []
def chk(name, cond):
    checks.append((name, cond))
    print(("PASS " if cond else "FAIL ") + name)

# 1 参军1600万约占总人口11% -> 隐含总人口约1.45亿
chk("1600万除以11%约1.45亿", abs(1600/0.11 - 14545) < 100)
# 2 18个月内除150万外全部退伍 -> 退伍1450万、占参军总数约90.6%
chk("退伍1450万占参军约90.6%", abs((1600-150)/1600 - 0.90625) < 1e-9)
# 3 短期利率0.38%维持7年、3个月国债低于2%（书中口径，本篇只核大小关系）
chk("0.38%低于2%上限", 0.38 < 2.0)
# 4 家庭负债：1945年294亿 -> 1955年1257亿约4.28倍 -> 1965年3312亿为1945年约11.27倍
chk("1955年负债约为1945年4.28倍", abs(1257/294 - 4.28) < 0.01)
chk("1965年负债约为1945年11.27倍", abs(3312/294 - 11.27) < 0.01)
# 5 汽车销量：1945-49年2100万辆 + 1949-55年3700万辆 = 5800万辆
chk("两段汽车销量合计5800万辆", 2100 + 3700 == 5800)
# 6 住房：1945-50年700万套 + 至1955年再800万套 = 1500万套，为1940-45年200万套的7.5倍
chk("战后十年住房1500万套为战时五年7.5倍", (700+800)/200 == 7.5)
# 7 1950年消费约2030亿美元、比1944年高约40% -> 1944年约1450亿
chk("2030亿除以1.4约1450亿", abs(2030/1.4 - 1450) < 1)
# 8 平均工资两次翻番 = 1940年基数的4倍
chk("两次翻番等于4倍", 2 * 2 == 4)
# 9 顶端1%收入占比13%降至7%：降6个百分点、相对降幅约46.2%
chk("13%降至7%相对降幅约46.2%", abs((13-7)/13 - 0.4615) < 0.001)
# 10 女性劳动参与率31% -> 37% -> 40%：单调上升、总升9个百分点
chk("女性参与率31到40共升9个百分点", 31 < 37 < 40 and 40 - 31 == 9)
# 11 1947-57年家庭债务涨5倍（书中口径）：期末为期初5倍、即净增400%
chk("涨5倍即净增400%", (5 - 1) * 100 == 400)
# 12 债务占收入比：约60% -> 130%以上 = 至少升70个百分点、倍数约2.17
chk("60%到130%倍数约2.17", abs(130/60 - 2.1667) < 0.001)
# 13 住房拥有率47% -> 53% -> 62%：两段分别升6与9个百分点
chk("拥有率两段升幅6与9个百分点", 53-47 == 6 and 62-53 == 9)
# 14 1973年前后短期利率2.5%升至8% = 3.2倍
chk("利率2.5%到8%为3.2倍", abs(8/2.5 - 3.2) < 1e-9)
# 15 标普500八年涨近4倍 -> 隐含年化约18.9%
chk("8年4倍隐含年化约18.9%", abs(4**(1/8) - 1 - 0.1892) < 0.001)
# 16 1993-2012年：顶端1%增86.1%、其余99%增6.6% -> 增速倍数约13.05
chk("86.1%约为6.6%的13.05倍", abs(86.1/6.6 - 13.045) < 0.01)
# 17 乔年入90万、彼得年薪8万 -> 乔为彼得的11.25倍、彼得约为乔的十一分之一
chk("90万除以8万等于11.25", 90/8 == 11.25)
# 18 彼得卡债4.5万、年薪8万 -> 卡债占年薪56.25%
chk("卡债占年薪约56%", abs(4.5/8 - 0.5625) < 1e-9)
# 19 汽车贷款12300美元涨至27900美元 -> 约2.27倍、确为一倍多
chk("车贷涨幅约2.27倍", abs(27900/12300 - 2.268) < 0.001)
# 20 还本付息占收入：低收入组超21%、最高组约8% -> 低收入组至少为最高组2.6倍
chk("21%至少为8%的2.6倍", 21/8 >= 2.6)

failed = [n for n, c in checks if not c]
print(f"{len(checks)-len(failed)}/{len(checks)} assertions passed")
raise SystemExit(1 if failed else 0)
