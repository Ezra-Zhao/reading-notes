#!/usr/bin/env python3
"""《金钱心理学》第19章验算：总结。只复核书中数字的算术含义与本篇计数。"""
ok = []
def chk(name, cond):
    ok.append(cond)
    print(("PASS" if cond else "FAIL"), name)

# 1 休斯案：被拔掉16颗牙（书中转述，B级）
chk("休斯被拔牙16颗", 16 == 16)
# 2 术后一周死亡 -> 1周=7天
chk("一周等于7天", 1 * 7 == 7)
# 3 医学院理念转变发生在「过去50年」-> 以成书2020年计，起点约1970年
chk("2020往前50年为1970", 2020 - 50 == 1970)
# 4 旧医疗观的两个前提：患者都想被治愈、存在通用正确的治疗方案
premises = ["每名患者都希望被治愈", "存在某种通用、正确的治疗方案"]
chk("旧医疗观前提恰为2条", len(premises) == 2)
# 5 本章建议清单计数（本篇归纳）：谦逊谅解、少虚荣、睡得踏实、拉长时间、错一半、买时间、
#    善意少奢侈、存钱、认清代价、容错空间、避免极端目标、爱风险避毁灭、认清游戏、尊重他人
advice = ["谦逊与谅解", "虚荣越少财富越多", "睡得踏实", "拉长时间", "错一半也没关系",
          "用财富买时间的掌控", "善意多于奢侈", "存钱", "明确并支付代价", "重视容错空间",
          "避免极端财务目标", "喜欢风险但警惕毁灭性风险", "明确所玩游戏的性质", "尊重每一个人"]
chk("本章建议共14条", len(advice) == 14)
# 6 「错了一半依然能积累财富」-> 错误率50%
chk("错一半等于错误率50%", abs(1 / 2 * 100 - 50) < 1e-9)
# 7 拉长时间的力量演示（自设情景）：年化5%下30年约为10年的2.65倍终值倍数
chk("5%三十年终值倍数约为十年2.65倍", abs((1.05 ** 30) / (1.05 ** 10) - 2.65) < 0.01)
# 8 虚荣与储蓄的恒等式（自设演示）：支出等于收入时，无论收入多高储蓄都为零
chk("支出等于收入则储蓄恒为零", all(inc - inc == 0 for inc in (100_000, 1_000_000, 10_000_000)))
# 9 时间不能抵消运气风险、但让结果更公平：尾部决定整体——少数几笔决定总结果，
#    演示：10笔中2笔各+100%、8笔各-10%，总结果仍为正（连乘）
r = (1 + 1.0) ** 2 * (1 - 0.1) ** 8
chk("错八成仍可为正的尾部演示", r > 1)
print(f"{sum(ok)}/{len(ok)} assertions passed")
assert all(ok)
