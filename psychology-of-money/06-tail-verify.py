# 2 风投分布：亏损65% + 10-20倍2.5% + 20倍以上1% + 50倍以上0.5%（后两档含于前档口径外单列时）
#    只验量级：拿到10倍以上的合计约4%，即约840家
assert abs(21000*(0.025+0.01+0.005) - 840) < 1e-9
# 3 罗素3000：40%大亏 + 贡献主力的7%，中间约53%平庸
assert abs((1 - 0.40 - 0.07) - 0.53) < 1e-9
# 4 苏/吉姆：435551 / 257386 约1.69倍，即苏多赚约69%，与书中约四分之三同量级
r = 435551/257386
assert 1.65 < r < 1.75, r
# 5 苏/汤姆：435551 / 234476 约1.86倍
r2 = 435551/234476
assert 1.80 < r2 < 1.92, r2
# 6 时间账：1900-2019共119年*12+? 按书中1428个月；300多个月衰退约22%
assert 1428 == 119*12
assert 0.20 < 314/1428 < 0.24
# 7 巴菲特：400-500只股票里大部分收益来自10只，即约2.0%-2.5%
assert 0.02 <= 10/500 and 10/400 <= 0.025
# 8 录用率：脸书0.1%是苹果约2%的二十分之一，谷歌0.2%是脸书的2倍
assert abs(0.02/0.001 - 20) < 1e-9 and abs(0.002/0.001 - 2) < 1e-9
# 9 林奇胜率：10次对6次 = 60%，错4次仍可赢的前提是赢时赚得多
assert 6/10 == 0.6
