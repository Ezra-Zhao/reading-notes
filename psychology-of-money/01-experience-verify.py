#!/usr/bin/env python3
"""《金钱心理学》第 01 篇验证脚本：核查第 1 章中可算的数字命题。

核查对象（均为书中给出的数字，本脚本只验算术与公开常数的一致性）：
1. 彩票支出比：低收入家庭年均买彩票 412 美元，是高收入家庭的 4 倍
   -> 高收入家庭应为 103 美元。
2. 第一张社保支票：1940 年艾达·梅·富勒领到 22.54 美元，书中说按通胀
   调整后约合 416 美元。用 BLS CPI-U 年均值（1940 年 14.0、2020 年
   258.8，成书年口径）换算应落在 410-420 美元区间。
3. 制度年龄：401(k) 诞生于 1978 年、Roth IRA 诞生于 1998 年；以成书年
   2020 年计，两者分别为 42 岁与 22 岁——与书中「Roth IRA 若是个人，
   刚到能饮酒的年龄（美国法定 21 岁）」的说法相符（22 >= 21 且差值 <=2）。
4. 应急金对照：书中并置的两个数字——低收入家庭年买彩票 412 美元，
   与「40% 美国人急需时拿不出 400 美元」——412 与 400 之差应小于 5%，
   即「一年彩票钱约等于一笔拿不出的应急钱」这一并置在算术上成立。
5. 退休概念的历史长度：以 1945 年（二战结束）到 2020 年计 75 年，
   按一代人 25-30 年折算为 2.5-3 代，与书中「退休概念最多不过两代人
   历史」的口径同量级（书中原意指其成为普遍期望的时段更短，此处只
   验量级不验字面）。

纯标准库，无外部数据文件。断言失败即退出码非零。
"""

# 1. 彩票支出比
low_income_lottery = 412
ratio = 4
high_income_lottery = low_income_lottery / ratio
assert high_income_lottery == 103, high_income_lottery
print(f"[1] 低收入家庭年彩票支出 412 美元 / 4 = 高收入家庭 {high_income_lottery:.0f} 美元 OK")

# 2. 社保首笔支票的通胀换算（BLS CPI-U 年均：1940=14.0，2020=258.8）
cpi_1940, cpi_2020 = 14.0, 258.8
converted = 22.54 * cpi_2020 / cpi_1940
assert 410 <= converted <= 420, converted
print(f"[2] 22.54 美元(1940) x CPI 258.8/14.0 = {converted:.1f} 美元(2020)，书中作 416 OK")

# 3. 制度年龄
age_401k = 2020 - 1978
age_roth = 2020 - 1998
assert age_401k == 42 and age_roth == 22
assert 0 <= age_roth - 21 <= 2
print(f"[3] 2020 年时 401(k) {age_401k} 岁、Roth IRA {age_roth} 岁，与「刚到饮酒年龄」口径相符 OK")

# 4. 412 与 400 的并置
gap = abs(low_income_lottery - 400) / 400
assert gap < 0.05, gap
print(f"[4] 年彩票支出 412 与应急门槛 400 之差 {gap:.1%}，并置成立 OK")

# 5. 退休概念历史量级
years = 2020 - 1945
for gen in (25, 30):
    g = years / gen
    assert 2.0 <= g <= 3.0, g
print(f"[5] 1945->2020 共 {years} 年，折 2.5-3.0 代，与「不过两代人」同量级 OK")

print("ALL CHECKS PASSED")
