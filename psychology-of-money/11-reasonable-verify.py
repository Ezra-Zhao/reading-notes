# 第11章验算：合乎情理胜过绝对理性
# 只复核书中数字的算术含义与自设情景，不作独立统计引用
# 1 发热疗效对照：康复率60% vs 约30% -> 2倍
assert abs(0.60/0.30 - 2.0) < 1e-9
# 2 体温升1°C病毒复制减至1/200 -> 减少99.5%
assert abs((1 - 1/200) - 0.995) < 1e-9
# 3 发热区间换算：100-104°F -> 37.8-40.0°C
lo = (100-32)*5/9; hi = (104-32)*5/9
assert abs(lo-37.78) < 0.01 and abs(hi-40.0) < 1e-9
# 4 耶鲁2:1杠杆：自有1+借入1=资产2，市场跌50% -> 资产1-负债1=权益0（清零）
equity = 2*(1-0.50) - 1
assert equity == 0
# 5 同策略声称退休财富高90% -> 终值比1.9倍
assert abs((1+0.90) - 1.9) < 1e-9
# 6 美股获胜概率阶梯（书中转述）：日50%<年68%<10年88%<20年100%，时间拉长单调升
p = [0.50, 0.68, 0.88, 1.00]
assert p == sorted(p) and p[-1] == 1.0
# 7 本土偏好：本土之外占95% -> 本土只占5%
assert abs((1-0.95) - 0.05) < 1e-9
# 8 马科维茨50/50自设情景：股市±30%、债券0%时，全股后悔落差60个点，50/50落差30个点，减半
full = 30 - (-30); half = (0.5*30) - (0.5*-30)
assert full == 60 and half == 30 and half == full/2
print("all 8 assertions passed")
