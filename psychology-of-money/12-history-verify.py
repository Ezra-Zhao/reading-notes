# 第12章验算：历史不是预言书
# 只复核书中数字的算术含义与自设情景，不作独立统计引用
# 1 19-20世纪出生约150亿人，书中点名6位关键人物 -> 占比4e-10，约每25亿人1位
frac = 6 / 15_000_000_000
assert abs(frac - 4e-10) < 1e-15 and abs(1/frac - 2_500_000_000) < 1.0
# 2 助学贷款链：总额1.6万亿美元、违约率10.8% -> 违约额约1728亿美元
assert abs(1.6 * 0.108 - 0.1728) < 1e-9
# 3 衰退间隔阶梯（书中转述）：约2年 < 5年 < 8年 < 12年，单调变长，12年为写作时最长间隔
gaps = [2, 5, 8, 12]
assert gaps == sorted(gaps) and gaps[-1] == 12
# 4 标普500结构：金融约16%，科技超过五分之一(>20%) -> 两者合计超过36%
assert 16 + 20 == 36
# 5 格雷厄姆公式版本年表：1934到1972共38年，其间多次改版；1976年去世，距首版42年
assert 1972 - 1934 == 38 and 1976 - 1934 == 42
# 6 401(k)写作时已诞生42年：以成书年2020倒推 -> 1978年，与该计划立法年份一致（算术核对）
assert 2020 - 42 == 1978
# 7 邓普顿口径：至少20%已变 -> 至多80%未变，变的部分不少于五分之一
assert abs((1 - 0.20) - 0.80) < 1e-9
# 8 自设情景：拿历史最坏跌幅50%当未来下限，实际跌60%时超出预设下限10个百分点、相对超出20%
assert 60 - 50 == 10 and abs((60-50)/50 - 0.20) < 1e-9
print("all 8 assertions passed")
