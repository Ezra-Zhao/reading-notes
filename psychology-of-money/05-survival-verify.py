# 验算脚本：《金钱心理学》第 5 章「致富 vs. 守富」可算命题复核
# clean-room 自写，只验算书中数字之间的关系，不引用原文。

# 1. 利弗莫尔：30 岁前身家约合今天 1 亿美元，1929 年崩盘一周做空一天进账约合今天 30 多亿美元
assert abs(3_000_000_000 / 100_000_000 - 30) < 1  # 单日进账约为其 30 岁前全部身家的 30 倍

# 2. 安全边际示例：同一笔钱滚 30 年，8% 与 4% 两种回报都活得下去，但终点差约 3.1 倍
hi = 1.08 ** 30
lo = 1.04 ** 30
assert abs(hi - 10.06) < 0.01 and abs(lo - 3.24) < 0.01
assert abs(hi / lo - 3.10) < 0.01

# 3. 福布斯 400：平均每 10 年约 20% 的人因非死亡、非家族转移原因掉榜
#    连掉 5 个十年后仍在榜的只剩约三分之一
assert abs(0.8 ** 5 - 0.3277) < 0.001

# 4. 书中引用的研究口径：曾成功上市的公司约 40% 后来失去全部价值，即约 60% 保住价值
assert 1 - 0.40 == 0.60

# 5. 美国过去约 170 年：33 次衰退累计约 48 年，衰退年份约占 28%
assert abs(48 / 170 - 0.282) < 0.001

# 6. 杠杆的生存账：标的跌 70% 时，2 倍杠杆的本金变动为 -140%，即本金归零且倒欠（示意模型）
assert 1 - 0.70 * 2 < 0  # 这正是盖林在 1973-1974 年被追缴保证金、被迫低价卖股的机制

# 7. 巴菲特的持久性：10 岁开始投资、89 岁以后仍在投，不间断约 79 年
assert 89 - 10 == 79

print("all 7 assertions passed")
