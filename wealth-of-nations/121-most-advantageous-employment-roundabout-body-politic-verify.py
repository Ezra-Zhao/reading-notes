# -*- coding: utf-8 -*-
"""验证《国富论》121 篇篇内数字与结构（原书第四卷第七章第三部分最有利用途段，Gutenberg #3300）。数字均为原书篇内陈述，不冒充现代实测，不构成投资建议。"""
# 1. 频率律：一千镑一年回一次维持一千、两次两千、三次三千
assert [1000 * n for n in (1, 2, 3)] == [1000, 2000, 3000]
# 2. 五年回一次只维持五分之一：一千镑乘五分之一恰两百镑
assert 1000 // 5 == 200
# 3. 烟草：年运入九万六千大桶减本国消费一万四千大桶恰八万二千大桶
assert 96000 - 14000 == 82000
# 4. 回程序位：直接三至四年小于迂回四至五年
assert (3, 4) < (4, 5)
# 5. 意外事件恰五件：暂时偶然四件、持续增长一件
assert 4 + 1 == 5
# 6. 独占强转方向恰三转：近邻到远方、直接到迂回、消费性外贸到转口贸易
assert len(["neighbouring to distant", "direct to round-about", "consumption to carrying"]) == 3
print("121 verify: 6 assertions passed")
