# -*- coding: utf-8 -*-
"""166 验证：公共土地地租不足与出售主张的结构与计数。参数取原书第五卷第二章第一部篇内陈述，不冒充现代实测。"""
# 1. 体量对照：常年收入逾 10,000,000 镑 > 土地税不足 2,000,000 镑的五倍；四先令/镑 = 五分之一
assert 10_000_000 >= 5 * 2_000_000  # 逾一千万对不足二百万：至少五倍量级（两数皆为原书约数边界）
assert 4 / 20 == 0.2
# 2. 三区土地税（整镑位）复算：伦敦 123,399 + 威斯敏斯特 63,092 + 宫区 30,754 = 217,245，伦敦居首
assert 123_399 + 63_092 + 30_754 == 217_245 and 123_399 > 63_092 > 30_754
# 3. 地租至多为产物三分之一：产物恰为地租三倍（按上限计）
assert 1 / 3 * 3 == 1.0
# 4. 算例复算：地租 10M→产物 30M、20M→60M；地主差 10M、大众差 30M 恰三倍
assert (20_000_000 - 10_000_000) * 3 == 60_000_000 - 30_000_000 == 30_000_000
# 5. 古代劳役：收获前 3 日 + 收获后 3 日 = 6 日；开支压低项恰四组
assert 3 + 3 == 6
assert len(["citizens serve at own expense", "feudal maintenance", "justice a revenue", "six days labour"]) == 4
# 6. 出售序位：改良地 30 年购买价 < 王地预期 40/50/60 年之下限；单一业主可得份额 < 四分之一上限登记
assert 30 < 40 < 50 < 60
assert 0.25 < 1.0
print("166 verify: 6 assertions passed")
