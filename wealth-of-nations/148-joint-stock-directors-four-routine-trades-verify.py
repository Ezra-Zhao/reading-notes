# -*- coding: utf-8 -*-
"""验证《国富论》148 篇篇内数字与结构（原书第五卷第一章第三部第一条后段：联股公司结构、败局与四业清单，Gutenberg #3300）。数字均为原书篇内陈述，不冒充现代实测，不构成投资建议。"""
# 1. 南海公司资本逾 £33,800,000，分半恰 £16,900,000；1733 年留存贸易股 £3,662,784:8:6 小于半数
assert 33_800_000 // 2 == 16_900_000 and 3_662_784 < 16_900_000
# 2. 年船十次航行仅一次（1731 皇家卡罗琳号）大赚；皇家非洲：1698 课私人冒险者 10%、1712 债权人 2/3 决议、1730 起年给 £10,000
assert 1 < 10 and 10 == 10 and 2 / 3 > 1 / 2 and 10_000 == 10_000
# 3. 哈德逊湾：常驻不逾 120 人、船停 6–8 周、资本不逾 £110,000（序位登记）
assert 120 == 120 and 6 < 8 and 110_000 < 744_000
# 4. 东印度：资本上限 £744,000 / 每股 £50 = 14,880 股；1698 年 £2,000,000×8% = £160,000 年息 > £700,000×4% = £28,000；旧公司认购 £315,000、私人分营 £7,200
assert 744_000 // 50 == 14_880 and 2_000_000 * 8 // 100 == 160_000 and 700_000 * 4 // 100 == 28_000 and 160_000 > 28_000 and 315_000 > 7_200
# 5. 分红门槛：政府贷款 £1,400,000 还清且债券债降至 £1,500,000 后方分 8%；余利四分之三入国库、四分之一留备
assert 1_400_000 < 1_500_000 and 3 + 1 == 4 and 8 == 8
# 6. 联股合理三情形恰三项；合例生意恰四种；莫雷莱清单 55 家
assert len(["reducible to routine/rule", "greater and more general utility", "capital beyond private copartnery"]) == 3 and len(["banking", "insurance", "canals", "water supply"]) == 4 and 55 == 55
print("148 verify: 6 assertions passed")
