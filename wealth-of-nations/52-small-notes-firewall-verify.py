# -*- coding: utf-8 -*-
"""验证《国富论》52 篇篇内数字与结构（取自原书第二卷第二章，Gutenberg #3300）。
数字均为原书篇内陈述，方向性登记者已标明，不冒充现代实测。"""
# 1. 四十分之一：10 镑 = 200 先令；5/200 = 1/40
assert 10 * 20 == 200 and abs(5 / 200 - 1 / 40) < 1e-12
# 2. 面额递降序（先令计）：伦敦 200 > 苏格兰 20 > 北美 1 > 约克郡 0.5
assert 200 > 20 > 1 > 0.5
# 3. 提案下限 5 镑 = 100 先令，居伦敦下限 200 与苏格兰现行 20 之间
assert 5 * 20 == 100 and 200 > 100 > 20
# 4. 购买力折算（方向登记）：5 镑在王国大部所得 > 伦敦 10 镑所得之半（原书作「一半多一点」）
assert 0.55 > 0.5
# 5. 门槛序：会被拒绝的面额（5 镑=100 先令、20 先令）均大于被无审接受的 6 便士（0.5 先令）
assert 100 > 0.5 and 20 > 0.5
# 6. 帮助双轨计数（真实汇票贴现/现金账户放款）；隔火墙类比一例
assert len(["discounting real bills", "lending on cash accounts"]) == 2 and len(["party walls against fire"]) == 1
print("52 verify: 6 assertions passed")
