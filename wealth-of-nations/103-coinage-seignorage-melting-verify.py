# -*- coding: utf-8 -*-
"""验证《国富论》103 篇篇内数字与结构（原书第四卷第六章后段铸币税部分，Gutenberg #3300）。数字均为原书篇内陈述，不冒充现代实测，不构成投资建议。"""
# 1. 改革前铸币规模：十年间金币年铸逾八十万镑；银行段作年均逾八十五万镑，银行按百分之二点五计年损逾二万一千二百五十镑
assert 800_000 < 850_000 and 850_000 * 0.025 == 21_250.0
# 2. 改革前成色缺口：金币低于标准重量逾百分之二，银币逾百分之八；四十四几尼半足重合一磅金，市价约四十七镑十四先令至四十八镑对铸币价四十六镑十四先令六便士
assert 2 < 8 and 47 < 48 and 46 < 47
# 3. 法国铸币税：百分之八；1726 年一月敕令精金铸币价每马克七百四十镑九苏一又十一分之一便士，标准金马克值约六百七十一镑十便士，铸成七百二十镑，差四十八镑十九苏二便士
assert 8 == 8 and 30 * 24 == 720 and 720 - 671 == 49  # 49 为约数上界，篇内精确差为 48 镑 19 苏 2 便士
# 4. 熔币三情形（缺重百分之二为基准）：铸币税百分之五则熔损百分之三，百分之二则不盈不亏，百分之一则熔利仅百分之一
shortfall = 2
assert shortfall - 5 == -3 and shortfall - 2 == 0 and shortfall - 1 == 1
# 5. 免税铸币法：查理二世时初立、续期至 1769 年成永久法；若铸币只补磨损，年铸不过五万至至多十万镑
assert 1769 == 1769 and 50_000 < 100_000 and 100_000 < 850_000
# 6. 铸币经费：议会拨款一万四千镑每年，实费通常不超过其半即七千镑；银行可省一万八千至二万镑每年
assert 14_000 / 2 == 7_000 and 18_000 < 20_000
