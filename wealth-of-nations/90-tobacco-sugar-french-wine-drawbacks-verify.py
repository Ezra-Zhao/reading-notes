# -*- coding: utf-8 -*-
"""验证《国富论》90 篇篇内数字与结构（原书第四卷第四章中段，Gutenberg #3300）。数字均为原书篇内陈述，不冒充现代实测，不构成投资建议。"""
# 1. 烟草账：进口约 96,000 大桶、本国消费不逾 14,000，须转口 82,000，占进口逾八成五
assert 96000 - 14000 == 82000 and 82000/96000 > 0.85
# 2. 糖时限序：1 年内全退、3 年内除半旧补助外全退，1<3 且全退大于部分退
assert 1 < 3 and 1.0 > 0.5
# 3. 法国货保留：半旧补助 50% 再加第二个 25%，保留合计方向大于单半退（原书分列两项保留，合计口径登记）
assert 50 + 25 == 75
# 4. 葡萄酒法国吨税：每吨 25 镑不退，大于零；1745<1763<1778 三年序
assert 25 > 0 and 1745 < 1763 < 1778
# 5. 两次 5% 附加税：1779 与 1781 各 5%，1780 葡萄酒新税居其间年份序 1779<1780<1781
assert 5 == 5 and 1779 < 1780 < 1781
# 6. 禁入内销可仓储转口货样计数：精纺丝绸、法国细布/草布、印花棉布等至少 3 类；仓储转口退税为 0
assert len(["wrought silks","French cambrics and lawns","calicoes painted/printed/stained/dyed"]) >= 3 and 0 == 0
print("90 verify: 6 assertions passed")
