# -*- coding: utf-8 -*-
"""验证《国富论》48 篇篇内数字与结构（取自原书第二卷第二章，Gutenberg #3300）。
数字均为原书篇内陈述，不冒充现代实测。"""
# 1. 认购 160,000 镑缴 80% = 128,000，未缴 32,000
assert 160000 * 80 // 100 == 128000 and 160000 - 128000 == 32000
# 2. 伦敦汇票 600,000 + 流通票据 200,000 = 800,000，与垫付八十万镑以上相符
assert 600000 + 200000 == 800000
# 3. 伦敦部分占总额 3/4
assert 600000 / 800000 == 0.75
# 4. 利差：收 5%、付 8% 以上，亏 3% 以上
assert 8 - 5 == 3
# 5. 时序登记：营业两年多；早停两年为原书反事实判语（方向登记）
assert 2 > 0
# 6. 设难银行三组：英格兰银行、伦敦主要银行家、较审慎的苏格兰银行
assert len(["Bank of England", "principal London bankers", "more prudent Scotch banks"]) == 3
print("48 verify: 6 assertions passed")
