# -*- coding: utf-8 -*-
"""验证《国富论》45 篇篇内数字与结构（取自原书第二卷第二章，Gutenberg #3300）。
数字均为原书篇内陈述，不冒充现代实测。"""
# 1. 上限律（方向性登记）：可容易流通的纸币总量 <= 其所替代的金银之值
def within_limit(paper, gold_silver_replaced):
    return paper <= gold_silver_replaced
assert within_limit(40_000, 40_000) and not within_limit(44_000, 40_000)
# 2. 算例：可吸收 40,000 镑，试发 44,000 镑，超额 4,000 镑为可吸收量的一成
assert 44_000 - 40_000 == 4_000 and 4_000 / 40_000 == 0.10
# 3. 备付：原备付 10,000（为可吸收额 25%）；按比例只需 11,000；实际须 14,000，多出 3,000
assert 10_000 / 40_000 == 0.25 and 44_000 * 0.25 == 11_000
assert 14_000 - 11_000 == 3_000 and 14_000 / 44_000 > 0.30
# 4. 英格兰银行年铸币区间 800,000–1,000,000 镑，原书「平均约 850,000」落于区间内
assert 800_000 <= 850_000 <= 1_000_000
# 5. 金块买入 4 镑/盎司 = 960 便士；铸出 3 镑17先令10.5便士 = 934.5 便士；
#    差 25.5 便士，约为买入价 2.7%，落入原书 2.5%–3% 区间
buy, issue = 4 * 240, 3 * 240 + 17 * 12 + 10.5
assert buy - issue == 25.5 and 0.025 <= (buy - issue) / buy <= 0.03
# 6. 苏格兰伦敦代理费下限 1.5% 加保险 0.75% 合计 2.25%；汇票往返「二三趟以上」即至少 2 趟
assert abs(1.5 + 0.75 - 2.25) < 1e-9 and 2 >= 2
print("45 verify: 6 assertions passed")
