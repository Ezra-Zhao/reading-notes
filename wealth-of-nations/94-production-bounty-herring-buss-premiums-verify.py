# -*- coding: utf-8 -*-
"""验证《国富论》94 篇篇内数字与结构（原书第四卷第五章后段，Gutenberg #3300）。数字均为原书篇内陈述，不冒充现代实测，不构成投资建议。"""
# 1. 海棍转可售鲱鱼三比二：378,347 * 2/3 约 252,231，与原书登记 252,231¼ 差在 1 桶内
assert abs(378347 * 2 / 3 - 252231.25) < 1
# 2. 吨位赏金分摊复核：每桶海棍 8 先令 2¼ 便士 = 8.1875 先令，乘总桶数除以 20 先令，与总额 155,463 镑同量级（差 <1%，尾数源于原书分摊取整）
total = 378347 * 8.1875 / 20
assert abs(total - 155463) / 155463 < 0.01
# 3. 外国盐腌出口一桶政府总成本：1 镑 7 先令 5¾ 便士 = 27 + 5.75/12 约 27.48 先令，大于平均市价一几尼 21 先令
assert abs((27 + 5.75 / 12) - 27.4792) < 0.001 and (27 + 5.75 / 12) > 21
# 4. 1759 年极端年：每桶海棍赏金 113 镑 15 先令 = 113.75 镑，全年仅 4 桶，赏金合计 455 镑
assert 113 + 15 / 20 == 113.75 and 4 * 113.75 == 455
# 5. 1750 年公司年金：每百镑年得 3 镑即 3%，50 万镑满额年年金 15,000 镑
assert 3 / 100 == 0.03 and 500000 * 0.03 == 15000
# 6. 分类计数：名实之辨三类工具（退税、赏金、奖品），国防例外货样两样（帆布、火药）
assert len(["drawback", "bounty", "premium"]) == 3 and len(["sail-cloth", "gunpowder"]) == 2
print("94 verify: 6 assertions passed")
