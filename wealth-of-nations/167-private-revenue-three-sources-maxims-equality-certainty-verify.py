# -*- coding: utf-8 -*-
"""167 验证：私人收入三源与税收四格言前两条的结构与计数。
参数全部取自《国富论》第五卷第二章第二部开题与格言一、二的篇内陈述，
只做结构/计数/排序断言，不冒充现代实测。纯标准库。"""

# 一、收入来源恰三样：地租、利润、工资，无第四源。
sources = ["地租", "利润", "工资"]
assert len(sources) == 3 and len(set(sources)) == 3

# 二、第二部按意图落点分条恰四条，顺序：地租、利润、工资、无差别三源。
articles = ["拟落于地租", "拟落于利润", "拟落于工资", "无差别落于三源"]
assert len(articles) == 4 and articles[0] == "拟落于地租" and articles[-1] == "无差别落于三源"

# 三、税收格言共四条，本篇覆盖前两条（平等、确定）。
maxims = ["平等", "确定", "便利", "经济"]
assert len(maxims) == 4 and maxims[:2] == ["平等", "确定"]

# 四、格言一出钱标准恰两表述（按能力、按保护下享有的收入比例）；
#    分摊比喻：义务主体=共同佃户，依据=各自权益。
maxim1_standards = ["按各自能力", "按国家保护下享有的收入之比例"]
assert len(maxim1_standards) == 2
estate = {"主体": "共同佃户", "依据": "各自在庄园中的权益"}
assert estate["主体"] == "共同佃户" and "权益" in estate["依据"]

# 五、格言二要求明白清楚的事项恰三项（时间、方式、数量），
#    公开对象含纳税人与任何其他人两类。
maxim2_clear_items = ["缴纳时间", "缴纳方式", "应纳数量"]
assert len(maxim2_clear_items) == 3
assert len(["纳税人", "任何其他人"]) == 2

# 六、危害排序：原书权重下，极小程度不确定之害 > 相当程度不平等之害。
harm = {"相当程度不平等": 1, "极小程度不确定": 2}
assert harm["极小程度不确定"] > harm["相当程度不平等"]

print("167 verify: 6 assertions passed")
