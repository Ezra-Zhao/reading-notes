# -*- coding: utf-8 -*-
"""验证《国富论》131 篇篇内数字与结构（原书第四卷第八章前段：反向引擎、原料进口免税与七种进口赏金，Gutenberg #3300）。数字均为原书篇内陈述，不冒充现代实测，不构成投资建议。"""
# 1. 棕色亚麻纱新税每磅 1 便士，小于旧税三档：帆纱 6 便士、法荷纱 1 先令=12 便士、云杉莫斯科纱每英担 £2:13:4=640 便士
new_duty_d = 1
assert new_duty_d < 6 < 12 < 640
# 2. 制纱劳动占制布总劳动 4/5，大于织布 1/5；供一名织工所需纺工为 3 至 4 名
assert 4 / 5 > 1 / 5 and 3 <= 4
# 3. 海军物资赏金下调链严格递减：焦油 4镑->2镑4先令=2.2镑、沥青 4镑->1镑、松节油 3镑->1镑10先令=1.5镑
assert 4 > 2.2 and 4 > 1 and 3 > 1.5
# 4. 靛蓝赏金 6 便士降 4 便士；大麻三期 8/6/4 镑严格递减且 1764+21=1785
assert 6 > 4 and 8 > 6 > 4 and 1764 + 21 == 1785
# 5. 生丝三期 25/20/15 镑严格递减；木材板材三期 20/15/10 先令（£1=20s）严格递减
assert 25 > 20 > 15 and 20 > 15 > 10
# 6. 进口原料赏金恰七种；原料进口鼓励恰两途（免税、赏金）
assert len(["naval stores", "indigo", "hemp/flax", "wood", "raw silk", "staves", "Irish hemp"]) == 7
assert len(["exemption from duties", "bounties"]) == 2
print("131 verify: 6 assertions passed")
