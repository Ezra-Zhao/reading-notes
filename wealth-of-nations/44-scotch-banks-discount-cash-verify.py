# -*- coding: utf-8 -*-
"""验证《国富论》44 篇篇内数字与结构（取自原书第二卷第二章，Gutenberg #3300）。
数字均为原书篇内陈述，不冒充现代实测。"""
# 1. 两家爱丁堡公立银行设立年：苏格兰银行 1695、皇家银行 1727，相差 32 年
assert 1727 - 1695 == 32
# 2. 流通今昔：联合前金银估不低于 1,000,000 镑；现今全流通估不低于 2,000,000 镑（为其两倍）；
#    现今金银部分不足 500,000 镑，即不足全流通的四分之一
assert 2_000_000 == 2 * 1_000_000
assert 500_000 < 2_000_000 / 4 + 1  # 不足五十万 < 二百万的四分之一即五十万（边界登记）
assert 500_000 == 2_000_000 // 4  # 五十万恰为二百万的四分之一，原书口径为「不足五十万」
# 3. 改铸银值 411,117 镑 < 联合前金银下限估一百万镑（金币、未送入银、英格兰币补足差额）
assert 411_117 < 1_000_000
# 4. 现金账户：举例额度 2,000–3,000 镑；借 1,000 镑在额度内；零星还款 20 与 30 镑的量级
assert 2_000 <= 3_000 and 1_000 <= 2_000
assert 1_000 // 20 == 50 and abs(30 / 1_000 - 0.03) < 1e-9
# 5. 伦敦商人对照：闲置备付 500 镑，周转一次之设例下恰等于一年少卖货值
idle, turnover = 500, 1
assert idle * turnover == 500
# 6. 票据流通信链六次传递构成闭环：银行→商人→制造商→农场主→地主→商人→银行（五类主体）
chain = ["bank", "merchant", "manufacturer", "farmer", "landlord", "merchant", "bank"]
assert len(chain) - 1 == 6 and chain[0] == chain[-1] == "bank" and len(set(chain)) == 5
print("44 verify: 6 assertions passed")
