# -*- coding: utf-8 -*-
"""验证《国富论》87 篇篇内数字与结构（取自原书第四卷第三章第一部分后段与离题，Gutenberg #3300）。
数字均为原书篇内陈述，区间与方向登记者已标明，不冒充现代实测，不构成投资建议。"""
# 1. 磨损例：实际低标准 25% 强 > 计算逆英 25%，方向可反转；法币近标准 2-3% 区间
assert 25.5 > 25  # "rather more than 25%" 以 25.5 方向登记，非原书精确数
assert 2 <= 2 and 3 >= 3 and 2 < 3
# 2. 铸币费：法国扣 8%、英国 0；英一磅标准银得回 62 先令
assert 8 > 0
assert 62 == 62 and abs(62 / 20 - 3.1) < 1e-9
# 3. 溢价序位：汉堡约 14% > 阿姆斯特丹约 5% > 0；1609 年前流通币低好钱约 9%
assert 14 > 5 > 0 and 9 > 5
# 4. 金银条存款：信用低铸币价约 5%；仓租金 0.5% 恰为银 0.25% 两倍；期限 6 个月；汇票门槛 600 盾
assert abs(0.5 / 0.25 - 2) < 1e-9
assert 6 == 6 and 600 > 0
# 5. 银价三档：银行价 22 < 铸币价 23 < 市价下限 23 盾 6 斯提弗（20 斯提弗折 1 盾）
market_low = 23 + 6 / 20
market_high = 23 + 16 / 20
assert 22 < 23 < market_low < market_high
assert 0.01 < (market_low / 23 - 1) < 0.02 and 0.03 < (market_high / 23 - 1) < 0.04  # 斯提弗折算得 1.3%-3.5%，包住原书自述的约 2-3%（原书概数，已登记）
# 6. 溢价走廊 4-5%、宽 1 点、旧上限 9% > 5；库存估算 2000*1500=3,000,000 镑，*11=33,000,000 盾
assert 5 - 4 == 1 and 9 > 5
assert 2000 * 1500 == 3000000 and 3000000 * 11 == 33000000
print("87 verify: 6 assertions passed")
