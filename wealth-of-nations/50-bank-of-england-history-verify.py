# -*- coding: utf-8 -*-
"""验证《国富论》50 篇篇内数字与结构（取自原书第二卷第二章，Gutenberg #3300）。
数字均为原书篇内陈述，镑先令便士按 1 镑=20 先令、1 先令=12 便士折算，不冒充现代实测。"""
def gbp(pounds, shillings=0, pence=0.0):
    return pounds + shillings / 20 + pence / 240
# 1. 年金构成：96000 利息 + 4000 管理费 = 100000；120 万镑的 8% 恰为 96000
assert 96000 + 4000 == 100000 and abs(1200000 * 0.08 - 96000) < 1e-9
# 2. 资本链：1697 总资本翻倍 = 4402343；再加两次催缴与原书总额在 0.01 镑内相符；再加 340 万镑得 8959995 量级
cap1697 = gbp(2201171, 10)
assert abs(cap1697 * 2 - 4402343) < 0.01
cap1710 = 4402343 + gbp(656204, 1, 9) + gbp(501448, 12, 11)
assert abs(cap1710 - gbp(5559995, 14, 8)) < 0.01
assert abs(cap1710 + 3400000 - gbp(8959995, 14, 8)) < 0.01
# 3. 预付链：3375027 + 200 万 = 5375027；再加南海购股 400 万 = 9375027（先令便士尾数同为 17s 10.5d）
assert 3375027 + 2000000 == 5375027 and 5375027 + 4000000 == 9375027
# 4. 1722 年起预付超过资本；1746 年预付 11686800 > 已分资本 10780000，差 906800
assert 9375027 > 8959995 and 11686800 - 10780000 == 906800
# 5. 利率序：8%（1694）> 6%（1708 法定与市场）> 3%（近年下限）；股息 5.5% 居其间
assert 0.08 > 0.06 > 0.03 and 0.03 < 0.055 < 0.08
# 6. 国库券折价三档递增；引擎职能四项（收付年金/流通国库券/预付土地税/预付麦芽税）
assert [40, 50, 60] == sorted([40, 50, 60]) and len(["annuities", "exchequer bills", "land tax", "malt tax"]) == 4
print("50 verify: 6 assertions passed")
